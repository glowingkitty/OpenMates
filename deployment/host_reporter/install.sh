#!/bin/sh
# Install or update the OpenMates host reporter on a core, upload or preview server.
#
#   sudo sh install.sh --role core \
#     --collector-url https://<collector-private-ip>:<port>/v1/host-report \
#     --collector-cert ./collector.crt --collector-tls-cert ./collector-tls.crt
#
# Idempotent: re-running updates the script, units and config and keeps the
# existing host signing key. Prints the public key line to register on dev.
# No network details are baked into this file; they come from the arguments.
set -eu

usage() {
  echo "usage: $0 --role core|upload|preview --collector-url URL --collector-cert FILE --collector-tls-cert FILE [--no-enable]" >&2
  exit 64
}

ROLE=""
URL=""
CERT=""
TLS_CERT=""
ENABLE=1
while [ $# -gt 0 ]; do
  case "$1" in
    --role) ROLE="${2:-}"; shift 2 ;;
    --collector-url) URL="${2:-}"; shift 2 ;;
    --collector-cert) CERT="${2:-}"; shift 2 ;;
    --collector-tls-cert) TLS_CERT="${2:-}"; shift 2 ;;
    --no-enable) ENABLE=0; shift ;;
    *) usage ;;
  esac
done

case "$ROLE" in core|upload|preview) ;; *) usage ;; esac
[ -n "$URL" ] && [ -f "$CERT" ] && [ -f "$TLS_CERT" ] || usage
[ "$(id -u)" -eq 0 ] || { echo "install.sh must run as root" >&2; exit 1; }
for tool in python3 ssh-keygen openssl curl dpkg-query apt-get ss systemctl; do
  command -v "$tool" >/dev/null 2>&1 || { echo "missing required tool: $tool" >&2; exit 1; }
done

SRC_DIR=$(CDPATH='' cd -- "$(dirname -- "$0")" && pwd)
LIB_DIR=/usr/local/lib/openmates/host-reporter
CONF_DIR=/etc/openmates/host-reporter
CONF_FILE=/etc/openmates/host-reporter.conf
UNIT_DIR=/etc/systemd/system
DROPIN_DIR="$UNIT_DIR/openmates-host-reporter.service.d"

# Validate the URL with the reporter's own rules (https, private address, fixed path)
# and extract the collector address for the systemd IP allowlist drop-in.
COLLECTOR_IP=$(python3 -I "$SRC_DIR/openmates-host-reporter" check-url "$URL")
for file in "$CERT" "$TLS_CERT"; do
  openssl x509 -in "$file" -noout >/dev/null 2>&1 || { echo "not a PEM certificate: $file" >&2; exit 1; }
done

install -d -m 0755 "$LIB_DIR" /etc/openmates "$DROPIN_DIR"
install -d -m 0700 "$CONF_DIR"
install -m 0755 "$SRC_DIR/openmates-host-reporter" "$LIB_DIR/openmates-host-reporter"
install -m 0644 "$SRC_DIR/README.md" "$LIB_DIR/README.md"
install -m 0644 "$CERT" "$CONF_DIR/collector.crt"
install -m 0644 "$TLS_CERT" "$CONF_DIR/collector-tls.crt"
for unit in openmates-host-facts-privileged.service openmates-host-reporter.service openmates-host-reporter.timer; do
  install -m 0644 "$SRC_DIR/systemd/$unit" "$UNIT_DIR/$unit"
done
install -m 0644 "$SRC_DIR/systemd/99openmates-host-report" /etc/apt/apt.conf.d/99openmates-host-report

umask 022
cat > "$CONF_FILE.tmp" <<EOF
# Written by deployment/host_reporter/install.sh; re-run it to change values.
ROLE=$ROLE
COLLECTOR_URL=$URL
DEPLOYED_IMAGES_FILE=/var/lib/openmates/deployed-images.json
EOF
mv "$CONF_FILE.tmp" "$CONF_FILE"

case "$COLLECTOR_IP" in *:*) PREFIX=128 ;; *) PREFIX=32 ;; esac
cat > "$DROPIN_DIR/collector-address.conf.tmp" <<EOF
# Generated by install.sh from --collector-url: the reporter may reach only the collector.
[Service]
IPAddressAllow=$COLLECTOR_IP/$PREFIX
EOF
mv "$DROPIN_DIR/collector-address.conf.tmp" "$DROPIN_DIR/collector-address.conf"

KEY="$CONF_DIR/host_ed25519"
if [ ! -f "$KEY" ]; then
  umask 077
  ssh-keygen -q -t ed25519 -N '' -C "openmates-host-report-$ROLE" -f "$KEY"
  rm -f "$KEY.pub"
fi
chown root:root "$KEY"
chmod 0600 "$KEY"

systemctl daemon-reload
if [ "$ENABLE" -eq 1 ]; then
  systemctl enable --now openmates-host-reporter.timer
fi

echo
echo "Register this host on the dev server (run in the OpenMates checkout):"
printf '  python3 scripts/security_monitoring/host_collector.py register-host --role %s --pubkey "%s"\n' \
  "$ROLE" "$(ssh-keygen -y -f "$KEY")"
echo
echo "Then send a first report:  systemctl start openmates-host-reporter.service"
echo "Check the result:          journalctl -u openmates-host-reporter.service -n 20"
