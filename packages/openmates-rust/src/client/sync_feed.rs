//! First-party incremental chat sync feed client (architecture.sync@2).
//!
//! A cold start (bounded phased sync) yields a cursor read before its snapshot
//! (`phased_sync_complete.sync_cursor`) plus the overview inputs
//! (`chat_overview_priority_ready`). A warm start replays only the changes
//! after that cursor with `chat_sync_delta_request`: encrypted metadata,
//! drafts and key wrappers, never transcript content. Pages are applied
//! idempotently (version guards, hash-only removals); a reset discards the
//! cursor and requires a cold start, never inferring deletions. The cursor and
//! overview inputs persist in the cache index section, scoped to the account or
//! Team context they came from. Reminder prompt previews are never persisted.
use super::overview::{ChatRank, OverviewEntry, OverviewInputs, ReminderInput, SavedItemInput};
use super::*;

pub(super) const SNAPSHOT_FIELD: &str = "chat_sync_feed_v1";
/// WebSocket `client_capabilities` entry that opts this socket into the feed.
pub const CAPABILITY: &str = "chat_sync_feed_v1";
const PAGE_LIMIT: u32 = 200;
const MAX_PAGES: usize = 50;
const PAGE_TIMEOUT: Duration = Duration::from_secs(30);
const MAX_CURSOR_LENGTH: usize = 160;
const MAX_DUE_ITEMS: usize = 200;
const REMOVAL_KINDS: [&str; 3] = ["deleted", "revoked", "moved"];

/// Persisted feed state of one account/Team context.
#[derive(Clone, Debug, Default, PartialEq)]
pub(super) struct FeedState {
    team: Option<String>,
    cursor: Option<String>,
    last_opened_chat_id: Option<String>,
    reminders: Vec<ReminderInput>,
    /// Encrypted saved-item memory rows exactly as the server sent them.
    saved_items: Vec<Value>,
    due_soon_generated_at: Option<i64>,
}

/// First feed page started before session admission completes (see `prefetch_chat_sync_feed`).
pub(super) struct FeedPrefetch {
    key: (String, String, String, Option<String>),
    #[cfg(not(target_arch = "wasm32"))]
    task: Option<tokio::task::JoinHandle<super::transport::SentRead>>,
}

#[cfg(not(target_arch = "wasm32"))]
impl Drop for FeedPrefetch {
    fn drop(&mut self) {
        if let Some(task) = &self.task {
            task.abort();
        }
    }
}

/// Cold-start feed facts observed during one phased sync.
#[derive(Default)]
pub(super) struct ColdStartCapture {
    cursor: Option<String>,
    overview: Option<Value>,
}

/// Outcome of a warm catch-up.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FeedCatchUp {
    /// Caught up; `changes` entries were applied over `pages` pages.
    Applied { pages: usize, changes: usize },
    /// No usable cursor (missing, other context, or server reset): run the bounded cold start.
    ColdStartRequired,
    /// The server declined for now (capability, rate limit, deferral): use the existing path.
    Unavailable,
}

/// Overview of the chat workspace in display order (see `overview`).
#[derive(Clone, Debug, PartialEq, serde::Serialize)]
pub struct WorkspaceOverview {
    pub entries: Vec<OverviewEntry>,
    pub last_opened_chat_id: Option<String>,
    /// Unix ms when the due-soon set was generated by the server, if known.
    pub due_soon_generated_at_ms: Option<i64>,
}

fn valid_cursor(value: &Value) -> Option<String> {
    value.as_str().filter(|c| !c.is_empty() && c.len() <= MAX_CURSOR_LENGTH && c.contains('|')).map(str::to_owned)
}

fn context_matches(payload: &Value, team: Option<&str>) -> bool {
    payload.get("team_id").and_then(Value::as_str).filter(|t| !t.is_empty()) == team
}

fn sanitized_reminder(value: &Value) -> Option<ReminderInput> {
    // Prompt previews are server-decrypted plaintext; keep only scheduling facts.
    let reminder = ReminderInput {
        reminder_id: value.get("reminder_id")?.as_str()?.to_owned(),
        trigger_at: value.get("trigger_at")?.as_i64()?,
        status: value.get("status").and_then(Value::as_str).unwrap_or_default().to_owned(),
        target_type: value.get("target_type").and_then(Value::as_str).unwrap_or_default().to_owned(),
        target_chat_id: value.get("target_chat_id").and_then(Value::as_str).map(str::to_owned),
        target_embed_id: value.get("target_embed_id").and_then(Value::as_str).map(str::to_owned),
    };
    Some(reminder)
}

impl FeedState {
    fn apply_due_soon(&mut self, due_soon: &Value) {
        let Some(due_soon) = due_soon.as_object() else { return };
        self.reminders = due_soon
            .get("reminders")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter_map(sanitized_reminder)
            .take(MAX_DUE_ITEMS)
            .collect();
        self.saved_items = due_soon
            .get("saved_items")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter(|row| row.get("encrypted_item_json").is_some_and(Value::is_string))
            .take(MAX_DUE_ITEMS)
            .cloned()
            .collect();
        self.due_soon_generated_at = due_soon.get("generated_at").and_then(Value::as_i64).map(|s| s * 1000);
    }

    fn apply_overview(&mut self, overview: &Value) {
        if let Some(opened) = overview.get("last_opened_chat_id") {
            self.last_opened_chat_id = opened.as_str().filter(|id| !id.is_empty()).map(str::to_owned);
        }
        if let Some(due_soon) = overview.get("due_soon").filter(|v| v.is_object()) {
            self.apply_due_soon(due_soon);
        }
    }

    fn snapshot(&self) -> Option<Value> {
        if self.cursor.is_none() && self.last_opened_chat_id.is_none() && self.reminders.is_empty() && self.saved_items.is_empty() {
            return None;
        }
        Some(json!({
            "version": 1,
            "team": self.team,
            "cursor": self.cursor,
            "last_opened_chat_id": self.last_opened_chat_id,
            "due_soon": {"reminders": self.reminders, "saved_items": self.saved_items, "generated_at_ms": self.due_soon_generated_at},
        }))
    }

    /// Malformed or other-context state is dropped (a cold start rebuilds it).
    fn restore(value: Option<&Value>, team: Option<&str>) -> Self {
        let Some(value) = value.filter(|v| v["version"] == 1) else { return Self::default() };
        let stored_team = value["team"].as_str().map(str::to_owned);
        if stored_team.as_deref() != team {
            return Self::default();
        }
        let due = &value["due_soon"];
        Self {
            team: stored_team,
            cursor: valid_cursor(&value["cursor"]),
            last_opened_chat_id: value["last_opened_chat_id"].as_str().map(str::to_owned),
            reminders: due["reminders"].as_array().into_iter().flatten()
                .filter_map(|r| serde_json::from_value(r.clone()).ok()).take(MAX_DUE_ITEMS).collect(),
            saved_items: due["saved_items"].as_array().cloned().unwrap_or_default().into_iter().take(MAX_DUE_ITEMS).collect(),
            due_soon_generated_at: due["generated_at_ms"].as_i64(),
        }
    }
}

/// Observe one phased-sync frame for the cold-start cursor and overview.
pub(super) fn observe_cold_start(kind: &str, payload: &Value, team: Option<&str>, capture: &mut ColdStartCapture) {
    if !context_matches(payload, team) {
        return;
    }
    match kind {
        "phased_sync_complete" => capture.cursor = payload.get("sync_cursor").and_then(valid_cursor),
        "chat_overview_priority_ready" => capture.overview = Some(payload.clone()),
        _ => {}
    }
}

/// SHA-256 hex of a chat ID (the server's `hashed_chat_id`).
fn hashed(id: &str) -> String {
    use sha2::{Digest, Sha256};
    Sha256::digest(id.as_bytes()).iter().map(|b| format!("{b:02x}")).collect()
}

fn version(row: &Value, field: &str) -> i64 {
    row.get(field).and_then(Value::as_i64).unwrap_or(0)
}

/// True when the cached row is strictly newer than the incoming one (stale replay).
fn cached_is_newer(cached: &Value, incoming: &Value) -> bool {
    let metadata = |row: &Value| version(row, "metadata_v").max(version(row, "title_v"));
    version(cached, "messages_v") > version(incoming, "messages_v") || metadata(cached) > metadata(incoming)
}

impl Client {
    /// Adopt the cursor and overview of a completed cold start for the current context.
    pub(super) fn adopt_cold_start_feed(&mut self, capture: ColdStartCapture) -> Result<()> {
        let team = self.team()?.map(str::to_owned);
        let mut state = if self.chat_sync_feed.team == team { self.chat_sync_feed.clone() } else { FeedState::default() };
        state.team = team;
        // A cold start without a cursor (older server, socket without the
        // capability) leaves no replay authority behind.
        state.cursor = capture.cursor;
        if let Some(overview) = &capture.overview {
            state.apply_overview(overview);
        }
        self.chat_sync_feed = state;
        Ok(())
    }

    pub(super) fn chat_sync_feed_snapshot(&self) -> Option<Value> {
        self.chat_sync_feed.snapshot()
    }

    pub(super) fn restore_chat_sync_feed(&mut self, snapshot: &Value) -> Result<()> {
        let team = self.team()?.map(str::to_owned);
        self.chat_sync_feed = FeedState::restore(snapshot.get(SNAPSHOT_FIELD), team.as_deref());
        Ok(())
    }

    /// Whether a warm catch-up is possible for the current context.
    pub fn has_chat_sync_cursor(&self) -> bool {
        self.team().ok().is_some_and(|team| self.chat_sync_feed.team.as_deref() == team) && self.chat_sync_feed.cursor.is_some()
    }

    fn feed_page_path(&self, cursor: &str) -> Result<String> {
        let mut path = self.scoped("/v1/chats/changes")?;
        path.push(if path.contains('?') { '&' } else { '?' });
        path.push_str(&format!(
            "cursor={}&limit={PAGE_LIMIT}",
            url::form_urlencoded::byte_serialize(cursor.as_bytes()).collect::<String>()
        ));
        Ok(path)
    }

    fn prefetch_key(&self, cursor: &str) -> Result<(String, String, String, Option<String>)> {
        let session = self.require_session()?;
        Ok((session.session_id.clone(), session.hashed_email.clone(), cursor.to_owned(), self.team()?.map(str::to_owned)))
    }

    /// Start the first feed page now, concurrently with the command's session
    /// admission (the two requests overlap their connection setup). The result
    /// is used only if, once admission has finished, the session, owner, Team
    /// and cursor are still the ones it was sent for; otherwise it is dropped
    /// (aborted) and the ordinary request runs. A no-op without a cursor.
    #[cfg(not(target_arch = "wasm32"))]
    pub fn prefetch_chat_sync_feed(&mut self) {
        self.feed_prefetch = None;
        let Some(cursor) = self.chat_sync_feed.cursor.clone().filter(|_| self.has_chat_sync_cursor()) else { return };
        let (Ok(key), Ok(path)) = (self.prefetch_key(&cursor), self.feed_page_path(&cursor)) else { return };
        let Ok(prepared) = self.prepare_read(Method::GET, &path, None, false) else { return };
        self.feed_prefetch = Some(FeedPrefetch { key, task: Some(tokio::spawn(prepared.send())) });
    }

    #[cfg(target_arch = "wasm32")]
    pub fn prefetch_chat_sync_feed(&mut self) {}

    /// The prefetched first page when it still matches this exact context.
    #[cfg(not(target_arch = "wasm32"))]
    async fn take_prefetched_page(&mut self, cursor: &str) -> Option<Result<Value>> {
        let mut prefetch = self.feed_prefetch.take()?;
        if self.prefetch_key(cursor).ok().as_ref() != Some(&prefetch.key) {
            return None;
        }
        let sent = prefetch.task.take()?.await.ok()?;
        Some(self.finish_read(sent).await.and_then(|value| value.ok_or(Error::Protocol)))
    }

    #[cfg(target_arch = "wasm32")]
    async fn take_prefetched_page(&mut self, _cursor: &str) -> Option<Result<Value>> {
        None
    }

    /// Replay every committed change after the stored cursor (warm start).
    /// One authenticated HTTPS request per page over the connection the command
    /// already holds (`GET /v1/chats/changes`): no second session validation and
    /// no WebSocket handshake. Transfers no transcript content; opening a chat
    /// never waits for this.
    pub async fn catch_up_chat_sync_feed(&mut self) -> Result<FeedCatchUp> {
        if !self.has_chat_sync_cursor() {
            return Ok(FeedCatchUp::ColdStartRequired);
        }
        let team = self.team()?.map(str::to_owned);
        let generation = self.generation;
        let cancel = self.operation_cancel.clone();
        let (mut pages, mut changes) = (0usize, 0usize);
        while pages < MAX_PAGES {
            let cursor = self.chat_sync_feed.cursor.clone().ok_or(Error::Protocol)?;
            let path = self.feed_page_path(&cursor)?;
            let prefetched = if pages == 0 { self.take_prefetched_page(&cursor).await } else { None };
            let response = match prefetched {
                // A prefetch that failed for any non-terminal reason is retried normally.
                Some(Ok(page)) => Ok(page),
                Some(Err(error @ (Error::Cancelled | Error::Expired))) => Err(error),
                Some(Err(_)) | None => tokio::select! {
                    biased;
                    _ = cancel.cancelled() => return Err(Error::Cancelled),
                    result = crate::platform::time::timeout(PAGE_TIMEOUT, self.request(Method::GET, &path, None)) => {
                        result.map_err(|_| Error::Offline)?
                    }
                },
            };
            if cancel.is_cancelled() || self.generation != generation || self.team()? != team.as_deref() {
                return Err(Error::Cancelled);
            }
            let payload = match response {
                Ok(payload) => payload,
                Err(Error::Forbidden) if team.is_some() => {
                    // Lost Team membership: prune only this Team's cached context.
                    self.forget_revoked_team_context();
                    return Err(Error::Forbidden);
                }
                Err(error @ (Error::Cancelled | Error::Expired)) => return Err(error),
                // Rate limit, deferral or transport failure: the caller keeps the existing path.
                Err(_) => return Ok(FeedCatchUp::Unavailable),
            };
            if payload["reset"] == true {
                // Never infer deletions from a reset; the cold start decides.
                self.chat_sync_feed.cursor = None;
                return Ok(FeedCatchUp::ColdStartRequired);
            }
            if !context_matches(&payload, team.as_deref()) {
                return Err(Error::Protocol);
            }
            changes += self.apply_chat_sync_page(&payload)?;
            pages += 1;
            if payload["has_more"] != true {
                return Ok(FeedCatchUp::Applied { pages, changes });
            }
        }
        // Bounded: the next run continues from the advanced cursor.
        Ok(FeedCatchUp::Applied { pages, changes })
    }

    /// The server rejected this Team: drop only this context's cached chats and feed state.
    fn forget_revoked_team_context(&mut self) {
        self.chats.clear();
        self.chat_arrival_order = Some(vec![]);
        self.wrappers.clear();
        self.history.clear();
        self.sync_message_windows.clear();
        self.selected_first_pages.clear();
        self.chat_sync_feed = FeedState::default();
        self.chat_list_freshness.invalidate();
    }

    fn remove_cached_chat(&mut self, id: &str) {
        self.chats.remove(id);
        if let Some(order) = self.chat_arrival_order.as_mut() {
            order.retain(|candidate| candidate != id);
        }
        self.history.remove(id);
        self.sync_message_windows.remove(id);
        self.selected_first_pages.remove(id);
        let hash = hashed(id);
        self.wrappers.retain(|wrapper| wrapper["hashed_chat_id"].as_str() != Some(hash.as_str()));
    }

    fn upsert_cached_row(&mut self, id: &str, row: Value) {
        if self.chats.insert(id.to_owned(), row).is_none()
            && let Some(order) = self.chat_arrival_order.as_mut()
        {
            order.push(id.to_owned());
        }
    }

    /// Apply one feed page; returns the number of entries applied. Idempotent.
    pub(super) fn apply_chat_sync_page(&mut self, page: &Value) -> Result<usize> {
        let next = page.get("next_cursor").and_then(valid_cursor).ok_or(Error::Protocol)?;
        let entries = page["changes"].as_array().ok_or(Error::Protocol)?;
        let mut applied = 0;
        for change in entries {
            let kinds: Vec<&str> = change["kinds"].as_array().ok_or(Error::Protocol)?.iter().filter_map(Value::as_str).collect();
            match change.get("chat_id").and_then(Value::as_str) {
                None => {
                    // Hash-only removal: deleted, revoked or moved out of this scope.
                    let hash = change["hashed_chat_id"].as_str().ok_or(Error::Protocol)?;
                    if !kinds.iter().any(|kind| REMOVAL_KINDS.contains(kind)) {
                        continue;
                    }
                    let matching: Vec<String> = self.chats.keys().filter(|id| hashed(id) == hash).cloned().collect();
                    for id in matching {
                        self.remove_cached_chat(&id);
                    }
                }
                Some(id) => {
                    if self.is_deleted_chat(id) {
                        continue;
                    }
                    if let Some(details) = change.get("chat_details").filter(|d| d.is_object()) {
                        if text(details, "id") != id {
                            return Err(Error::Protocol);
                        }
                        let stale = self.chats.get(id).is_some_and(|cached| cached_is_newer(cached, details));
                        if !stale {
                            self.upsert_cached_row(id, details.clone());
                        }
                        if let Some(wrappers) = change.get("chat_key_wrappers").and_then(Value::as_array) {
                            for wrapper in wrappers {
                                let wrapper_id = wrapper.get("id").cloned();
                                self.wrappers.retain(|existing| wrapper_id.is_none() || existing.get("id") != wrapper_id.as_ref());
                                self.wrappers.push(wrapper.clone());
                            }
                        }
                    } else if let Some(draft) = change.get("draft").filter(|d| d.is_object()) {
                        self.apply_draft_only_change(id, draft);
                    }
                }
            }
            applied += 1;
        }
        if let Some(overview) = page.get("overview").filter(|v| v.is_object()) {
            self.chat_sync_feed.apply_overview(overview);
        }
        self.chat_sync_feed.cursor = Some(next);
        Ok(applied)
    }

    /// Draft-only chat (no chat row on the server): create, update or remove it.
    fn apply_draft_only_change(&mut self, id: &str, draft: &Value) {
        let draft_v = version(draft, "draft_v");
        let markdown = draft.get("encrypted_draft_md").and_then(Value::as_str).filter(|v| !v.is_empty());
        if markdown.is_none() && self.chats.get(id).is_some_and(super::sync::draft_only) {
            let id = id.to_owned();
            self.remove_cached_chat(&id);
            return;
        }
        match (self.chats.get_mut(id), markdown) {
            (Some(row), Some(markdown)) => {
                if version(row, "draft_v") <= draft_v {
                    row["encrypted_draft_md"] = json!(markdown);
                    row["encrypted_draft_preview"] = draft["encrypted_draft_preview"].clone();
                    row["draft_v"] = json!(draft_v);
                }
            }
            (Some(row), None) => {
                row["encrypted_draft_md"] = Value::Null;
                row["encrypted_draft_preview"] = Value::Null;
                row["draft_v"] = json!(0);
            }
            (None, Some(markdown)) => {
                let now = (crate::platform::unix_ms() / 1000) as i64;
                self.upsert_cached_row(id, json!({
                    "id": id, "type": "new_chat", "messages_v": 0, "title_v": 0, "metadata_v": 0,
                    "draft_v": draft_v, "last_edited_overall_timestamp": now, "created_at": now, "updated_at": now,
                    "encrypted_title": null, "encrypted_draft_md": markdown,
                    "encrypted_draft_preview": draft["encrypted_draft_preview"].clone(),
                }));
            }
            (None, None) => {}
        }
    }

    /// The workspace overview in display order: due-soon items, the last opened
    /// chat, then parent chats (`overview::build_overview`). Saved items stay
    /// encrypted here; adapters decrypt them with the memories key to show titles.
    pub fn workspace_overview(&self, now_ms: i64, utc_offset_minutes: i32, saved_items: &[SavedItemInput]) -> WorkspaceOverview {
        let ranks: Vec<ChatRank> = self.chats.values().filter_map(ChatRank::from_row).collect();
        let state = &self.chat_sync_feed;
        let inputs = OverviewInputs {
            chats: &ranks,
            last_opened_chat_id: state.last_opened_chat_id.as_deref(),
            reminders: &state.reminders,
            saved_items,
            now_ms,
            utc_offset_minutes,
            include_sub_chats: false,
        };
        WorkspaceOverview {
            entries: super::overview::build_overview(&inputs),
            last_opened_chat_id: state.last_opened_chat_id.clone(),
            due_soon_generated_at_ms: state.due_soon_generated_at,
        }
    }

    /// `chats list` warm path: one feed catch-up over the cached index, then
    /// the rendered list in overview order. None means "use the existing
    /// bounded sync path" (no cursor, reset, deferral or transport failure);
    /// that path reports its own errors. Cancellation and expiry propagate.
    pub async fn chat_list_from_feed(&mut self) -> Result<Option<Vec<Item>>> {
        match self.catch_up_chat_sync_feed().await {
            Ok(FeedCatchUp::Applied { .. }) => {}
            Ok(FeedCatchUp::ColdStartRequired | FeedCatchUp::Unavailable) => return Ok(None),
            Err(error @ (Error::Cancelled | Error::Expired | Error::Forbidden)) => return Err(error),
            Err(_) => return Ok(None),
        }
        let items = self.render_chat_inventory_with_capability().await?;
        Ok(Some(self.order_chat_list_items_now(items)))
    }

    /// `order_chat_list_items` at the current time and the adapter-provided
    /// local UTC offset (`overview::set_local_utc_offset_minutes`; zone-less
    /// times are local, as in the web app).
    pub fn order_chat_list_items_now(&self, items: Vec<Item>) -> Vec<Item> {
        self.order_chat_list_items(items, crate::platform::unix_ms() as i64, super::overview::local_utc_offset_minutes())
    }

    /// Decrypted saved-item memories of the due-soon set (rows that do not
    /// decrypt or are not objects are skipped, like the memories reader).
    pub fn due_soon_saved_items(&self) -> Vec<SavedItemInput> {
        let Ok(session) = self.require_session() else { return vec![] };
        let master = session.master_key.clone();
        let field = |row: &Value, name: &str| row.get(name).and_then(Value::as_str).unwrap_or_default().to_owned();
        self.chat_sync_feed
            .saved_items
            .iter()
            .filter_map(|row| {
                let ciphertext = row.get("encrypted_item_json")?.as_str()?;
                let plaintext = zeroize::Zeroizing::new(crate::crypto::decrypt_combined(ciphertext, &master).ok()?);
                let value: Value = serde_json::from_str(&plaintext).ok()?;
                value.is_object().then(|| SavedItemInput {
                    entry_id: field(row, "id"),
                    app_id: field(row, "app_id"),
                    item_type: field(row, "item_type"),
                    item_value: value,
                })
            })
            .collect()
    }

    /// Encrypted saved-item memory rows of the due-soon set (decrypt with the memories key).
    pub fn due_soon_saved_item_rows(&self) -> &[Value] {
        &self.chat_sync_feed.saved_items
    }

    /// Order rendered chat list items like the overview (due chats, last opened,
    /// then pinned, draft, recency, ID); sub-chats keep their comparator position.
    pub fn order_chat_list_items(&self, items: Vec<Item>, now_ms: i64, utc_offset_minutes: i32) -> Vec<Item> {
        let ranks: Vec<ChatRank> = self.chats.values().filter_map(ChatRank::from_row).collect();
        let state = &self.chat_sync_feed;
        let order = super::overview::ordered_chat_ids(&OverviewInputs {
            chats: &ranks,
            last_opened_chat_id: state.last_opened_chat_id.as_deref(),
            reminders: &state.reminders,
            saved_items: &[],
            now_ms,
            utc_offset_minutes,
            include_sub_chats: true,
        });
        let position: BTreeMap<&str, usize> = order.iter().enumerate().map(|(index, id)| (id.as_str(), index)).collect();
        let mut items = items;
        // Stable: items without a cached row keep their relative order at the end.
        items.sort_by_key(|item| position.get(item.id.as_str()).copied().unwrap_or(usize::MAX));
        items
    }
}

