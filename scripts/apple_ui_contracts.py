def missing_attachment_icons(source: str, available_icons: set[str]) -> set[str]:
    return set(re.findall(r'\b(?:Icon|item)\("([^"]+)"', source)) - available_icons


def audit_message_input() -> tuple[list[str], list[str]]:
    errors = validate_contract(MESSAGE_INPUT_FIXTURE, surface="message-input")
    warnings: list[str] = []
    source = "\n".join(path.read_text(encoding="utf-8") for path in swift_files_for_message_input())

    for identifier in sorted(REQUIRED_MESSAGE_INPUT_IDENTIFIERS):
        if f'"{identifier}"' not in source:
            errors.append(f"missing Apple accessibility identifier: {identifier}")

    attachment_row = (REPO_ROOT / "apple/OpenMates/Sources/Shared/Composer/ComposerAttachmentActionRow.swift").read_text(encoding="utf-8")
    icon_sources = REPO_ROOT / "frontend/packages/ui/static/icons"
    available_icons = {path.stem for path in icon_sources.glob("*.svg")}
    for icon in sorted(missing_attachment_icons(attachment_row, available_icons)):
        errors.append(f"missing Apple attachment icon source: {icon}.svg")
    for action in ("drawing", "location", "camera", "files"):
        if not re.search(rf'item\([^,\n]+,\s*[^,\n]+,\s*"{action}"', attachment_row):
            errors.append(f"missing Apple attachment menu action: {action}")

    forbidden_controls = ["Form {", "List {", "NavigationLink {", ".navigationTitle(", ".toolbar {"]
    for forbidden in forbidden_controls:
        if forbidden in source:
            errors.append(f"forbidden native product control in message input source: {forbidden}")

    warnings.append("visual/style contract checks are warning-only for message-input until promoted")
    return errors, warnings


def audit_settings() -> tuple[list[str], list[str]]:
    errors = validate_contract(SETTINGS_FIXTURE, surface="settings")
    warnings = ["visual/style contract checks are warning-only for settings until promoted"]
    return errors, warnings


def audit_surface(surface: str) -> tuple[list[str], list[str]]:
    if surface == "message-input":
        return audit_message_input()
    if surface == "embeds":
        return audit_embeds()
    if surface == "settings":
        return audit_settings()
    raise ContractError(f"unsupported audit surface: {surface}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    validate_parser = subparsers.add_parser("validate")
    validate_parser.add_argument("path", type=Path)
    validate_parser.add_argument("--surface")

    promote_parser = subparsers.add_parser("promote")
    promote_parser.add_argument("source", type=Path)
    promote_parser.add_argument("--destination", type=Path)

    audit_parser = subparsers.add_parser("audit")
    audit_parser.add_argument("--surface", required=True, choices=["message-input", "embeds", "settings"])
    audit_parser.add_argument("--web-root", type=Path, help="Embed audit web source root; defaults to this checkout")
    audit_parser.add_argument("--native-root", type=Path, help="Embed audit Apple source root; defaults to this checkout")

    args = parser.parse_args()
    try:
        if args.command == "validate":
            errors = validate_contract(args.path, surface=args.surface)
            if errors:
                for error in errors:
                    print(f"ERROR: {error}", file=sys.stderr)
                return 1
            print(f"PASS {args.path}")
            return 0

        if args.command == "promote":
            promote_contract(args.source, args.destination)
            print(f"PROMOTED {args.source} -> {args.destination}")
            return 0

        if args.command == "audit":
            if args.surface != "embeds" and (args.web_root or args.native_root):
                raise ContractError("--web-root/--native-root apply only to the embeds audit")
            errors, warnings = (audit_embeds(web_root=args.web_root, native_root=args.native_root)
                                if args.surface == "embeds" else audit_surface(args.surface))
            for warning in warnings:
                print(f"WARNING: {warning}")
            if errors:
                for error in errors:
                    print(f"ERROR: {error}", file=sys.stderr)
                return 1
            print(f"PASS {args.surface} audit")
            return 0
    except ContractError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    return 1


if __name__ == "__main__":
    raise SystemExit(main())
