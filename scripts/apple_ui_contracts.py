class ContractError(Exception):
    """Raised for contract validation or audit failures."""


def load_contract(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ContractError(f"contract file not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ContractError(f"invalid JSON in {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise ContractError("contract root must be an object")
    return data


def walk_values(value: Any) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        values: list[str] = []
        for item in value:
            values.extend(walk_values(item))
        return values
    if isinstance(value, dict):
        values = []
        for item in value.values():
            values.extend(walk_values(item))
        return values
    return []


def validate_contract(path: Path, *, surface: str | None = None) -> list[str]:
    contract = load_contract(path)
    errors: list[str] = []

    if contract.get("schemaVersion") != 1:
        errors.append("schemaVersion must be 1")
    if not isinstance(contract.get("surface"), str):
        errors.append("surface must be a string")
    if surface and contract.get("surface") != surface:
        errors.append(f"surface must be {surface!r}")
    if not isinstance(contract.get("generatedAt"), str) and contract.get("surface") != "embeds":
        errors.append("generatedAt must be a string")
    viewport = contract.get("viewport")
    if contract.get("surface") != "embeds" and (
        not isinstance(viewport, dict) or not isinstance(viewport.get("width"), int) or not isinstance(viewport.get("height"), int)
    ):
        errors.append("viewport.width and viewport.height must be integers")

    if contract.get("surface") == "embeds":
        return errors + validate_embeds_contract(contract)

    states = contract.get("states")
    if not isinstance(states, list) or not states:
        errors.append("states must be a non-empty array")
        states = []

    state_ids: set[str] = set()
    test_ids_by_state: dict[str, set[str]] = {}
    for state in states:
        if not isinstance(state, dict):
            errors.append("state entries must be objects")
            continue
        state_id = state.get("id")
        if not isinstance(state_id, str) or not state_id:
            errors.append("state.id must be a non-empty string")
        else:
            state_ids.add(state_id)
            test_ids_by_state[state_id] = set()
        elements = state.get("elements")
        if not isinstance(elements, list) or not elements:
            errors.append(f"state {state_id or '<unknown>'} must contain elements")
            continue
        for element in elements:
            if not isinstance(element, dict):
                errors.append(f"state {state_id} has a non-object element")
                continue
            for required_field in ("semanticId", "testId", "severity", "structure", "computedStyle"):
                if required_field not in element:
                    errors.append(f"state {state_id} element missing {required_field}")
            if element.get("severity") not in ALLOWED_SEVERITIES:
                errors.append(f"state {state_id} has invalid severity {element.get('severity')!r}")
            if element.get("required", True) and element.get("exists") is not True:
                errors.append(f"state {state_id} required element {element.get('testId')} does not exist")
            if (
                isinstance(state_id, str)
                and state_id in test_ids_by_state
                and isinstance(element.get("testId"), str)
            ):
                test_ids_by_state[state_id].add(element["testId"])

    if contract.get("surface") == "message-input":
        missing_states = REQUIRED_MESSAGE_INPUT_STATES - state_ids
        if missing_states:
            errors.append(f"missing message-input states: {', '.join(sorted(missing_states))}")

    if contract.get("surface") == "settings":
        missing_states = REQUIRED_SETTINGS_STATES - state_ids
        if missing_states:
            errors.append(f"missing settings states: {', '.join(sorted(missing_states))}")
        for state_id, required_test_ids in REQUIRED_SETTINGS_TEST_IDS_BY_STATE.items():
            missing_test_ids = required_test_ids - test_ids_by_state.get(state_id, set())
            if missing_test_ids:
                errors.append(f"state {state_id} missing settings test IDs: {', '.join(sorted(missing_test_ids))}")
        if viewport != SETTINGS_VIEWPORT:
            errors.append("settings viewport must be 390x844")

    for value in walk_values(contract):
        for pattern in PRIVATE_VALUE_PATTERNS:
            if pattern.search(value):
                errors.append(f"contract contains private or volatile value matching {pattern.pattern!r}")
                break

    return errors


def validate_embeds_contract(contract: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    dimension = contract.get("dimension")
    if not isinstance(dimension, dict) or not isinstance(dimension.get("id"), str):
        errors.append("embeds contract requires dimension.id")

    apps = contract.get("apps")
    if not isinstance(apps, list) or not apps:
        errors.append("embeds contract requires a non-empty apps array")
        apps = []
    app_ids = {app.get("appId") for app in apps if isinstance(app, dict) and isinstance(app.get("appId"), str)}
    missing_apps = REQUIRED_EMBED_SHOWCASE_APPS - app_ids
    if missing_apps:
        errors.append(f"embeds contract missing apps: {', '.join(sorted(missing_apps))}")

    surfaces = contract.get("surfaces")
    if not isinstance(surfaces, list) or not surfaces:
        errors.append("embeds contract requires a non-empty surfaces array")
        surfaces = []
    for surface_entry in surfaces:
        if not isinstance(surface_entry, dict):
            errors.append("embeds contract surface entries must be objects")
            continue
        key = surface_entry.get("key")
        if not isinstance(key, str) or not key:
            errors.append("embeds contract surface entry missing key")
        if surface_entry.get("appId") not in app_ids:
            errors.append(f"embeds contract surface {key or '<unknown>'} references unknown appId")
        sources = surface_entry.get("sources")
        if not isinstance(sources, dict) or sources.get("preview") is not True or sources.get("fullscreen") is not True:
            errors.append(f"embeds contract surface {key or '<unknown>'} must include preview and fullscreen sources")
        previews = surface_entry.get("previews")
        if not isinstance(previews, list) or not previews:
            errors.append(f"embeds contract surface {key or '<unknown>'} must include preview captures")
        fullscreen = surface_entry.get("fullscreen")
        if not isinstance(fullscreen, dict):
            errors.append(f"embeds contract surface {key or '<unknown>'} must include fullscreen capture")
        # Legacy per-app surfaces remain useful DOM contracts, but requiring
        # separate section/fullscreen PNGs duplicates the exhaustive registry
        # captures below. Keep the complete DOM inventory without hundreds of
        # redundant screenshots.

    registry_surfaces = contract.get("registrySurfaces")
    if not isinstance(registry_surfaces, list):
        errors.append("embeds contract requires registrySurfaces array")
        registry_surfaces = []

    if isinstance(dimension, dict) and dimension.get("id") in REQUIRED_EMBED_REGISTRY_DIMENSIONS:
        registry_source = _read_repo_file("frontend/packages/ui/src/data/embedRegistry.generated.ts")
        preview_keys = _extract_ts_object_keys(registry_source, "EMBED_PREVIEW_COMPONENTS")
        fullscreen_keys = _extract_ts_object_keys(registry_source, "EMBED_FULLSCREEN_COMPONENTS")
        expected = {(key, "preview") for key in preview_keys} | {
            (key, "fullscreen") for key in fullscreen_keys
        }
        actual: set[tuple[str, str]] = set()
        for entry in registry_surfaces:
            if not isinstance(entry, dict):
                errors.append("embeds contract registry surface entries must be objects")
                continue
            key, surface = entry.get("registryKey"), entry.get("surface")
            if not isinstance(key, str) or surface not in {"preview", "fullscreen"}:
                errors.append("embeds contract registry surface has invalid key or surface")
                continue
            identity = (key, surface)
            if identity in actual:
                errors.append(f"embeds contract has duplicate registry surface: {key}:{surface}")
            actual.add(identity)
            if entry.get("exists") is not True or entry.get("renderError") is True:
                errors.append(f"embeds contract registry surface did not render: {key}:{surface}")
            if not isinstance(entry.get("capture"), dict):
                errors.append(f"embeds contract registry surface missing rendered capture: {key}:{surface}")
            screenshot = entry.get("screenshotPath")
            if not isinstance(screenshot, str) or not screenshot.strip():
                errors.append(f"embeds contract registry surface missing screenshot: {key}:{surface}")
            elif screenshot.startswith(("/", "~")) or re.match(r"^[A-Za-z]:[/\\]", screenshot):
                errors.append(f"embeds contract registry screenshot must be relative: {key}:{surface}")

        missing = sorted(expected - actual)
        extra = sorted(actual - expected)
        if missing:
            errors.append(
                f"embeds contract missing {len(missing)} registry surfaces: "
                + ", ".join(f"{key}:{surface}" for key, surface in missing[:8])
            )
        if extra:
            errors.append(
                f"embeds contract has {len(extra)} unknown registry surfaces: "
                + ", ".join(f"{key}:{surface}" for key, surface in extra[:8])
            )

    for value in walk_values(contract):
        for pattern in PRIVATE_VALUE_PATTERNS:
            if pattern.search(value):
                errors.append(f"contract contains private or volatile value matching {pattern.pattern!r}")
                break

    return errors


def _read_repo_file(relative_path: str) -> str:
    return (REPO_ROOT / relative_path).read_text(encoding="utf-8")


def _extract_ts_object_keys(source: str, const_name: str) -> set[str]:
    match = re.search(
        rf"export const {re.escape(const_name)}:[^=]+=\s*{{(?P<body>.*?)^}};",
        source,
        flags=re.DOTALL | re.MULTILINE,
    )
    if not match:
        return set()
    return set(re.findall(r'^[ \t]*"([^"]+)"[ \t]*:', match.group("body"), flags=re.MULTILINE))


def _extract_showcase_apps(source: str) -> set[str]:
    match = re.search(r"export const EMBED_APP_SLUGS = \[(?P<body>.*?)\] as const;", source, flags=re.DOTALL)
    if not match:
        return set()
    return set(re.findall(r"'([^']+)'", match.group("body")))


def _extract_swift_enum_raw_values(source: str, enum_name: str) -> set[str]:
    match = re.search(rf"enum {re.escape(enum_name)}[^{{]*{{(?P<body>.*?)^}}", source, flags=re.DOTALL | re.MULTILINE)
    if not match:
        return set()
    values: set[str] = set()
    for line in match.group("body").splitlines():
        stripped = line.strip()
        if not stripped.startswith("case "):
            continue
        if "=" in stripped:
            raw_match = re.search(r'=\s*"([^"]+)"', stripped)
            if raw_match:
                values.add(raw_match.group(1))
        else:
            for name in stripped.removeprefix("case ").split(","):
                name = name.strip()
                if not name:
                    continue
                case_name = name.split()[0]
                if case_name:
                    values.add(case_name)
    return values


def _extract_swift_enum_cases(source: str, enum_name: str) -> set[str]:
    match = re.search(rf"enum {re.escape(enum_name)}[^{{]*{{(?P<body>.*?)^}}", source, flags=re.DOTALL | re.MULTILINE)
    if not match:
        return set()
    cases: set[str] = set()
    for line in match.group("body").splitlines():
        stripped = line.strip()
        if not stripped.startswith("case "):
            continue
        for name in stripped.removeprefix("case ").split(","):
            case_name = name.strip().split("=")[0].strip().split()[0]
            if case_name:
                cases.add(case_name)
    return cases


def _extract_swift_enum_raw_value_to_case(source: str, enum_name: str) -> dict[str, str]:
    match = re.search(rf"enum {re.escape(enum_name)}[^{{]*{{(?P<body>.*?)^}}", source, flags=re.DOTALL | re.MULTILINE)
    if not match:
        return {}
    raw_to_case: dict[str, str] = {}
    for line in match.group("body").splitlines():
        stripped = line.strip()
        if not stripped.startswith("case "):
            continue
        for entry in stripped.removeprefix("case ").split(","):
            entry = entry.strip()
            if not entry or entry.startswith("."):
                continue
            case_name = entry.split("=")[0].strip().split()[0]
            if not case_name:
                continue
            raw_match = re.search(r'=\s*"([^"]+)"', entry)
            raw_to_case[raw_match.group(1) if raw_match else case_name] = case_name
    return raw_to_case


def _extract_apple_fixture_skill_ids(source: str) -> set[str]:
    direct = re.findall(r"\bskill\(id:\s*\"([^\"]+)\"", source)
    helper_calls = re.findall(r"calendarAction\(id:\s*\"([^\"]+)\"", source)
    return set(direct + helper_calls)


def _swift_mask(source: str) -> str:
    """Mask comments/strings without changing positions for balanced Swift blocks."""
    return re.sub(
        r'//[^\n]*|/\*.*?\*/|""".*?"""|"(?:\\.|[^"\\])*"',
        lambda match: re.sub(r"[^\n]", " ", match.group()), source, flags=re.DOTALL,
    )


def _swift_without_comments(source: str) -> str:
    return re.sub(
        r'""".*?"""|"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/',
        lambda match: re.sub(r"[^\n]", " ", match.group()) if match.group().startswith(("//", "/*")) else match.group(),
        source, flags=re.DOTALL,
    )


def _swift_block(source: str, anchor: str) -> str:
    match = re.search(anchor, source)
    if not match:
        return ""
    mask = _swift_mask(source)
    start = mask.find("{", match.end())
    if start < 0:
        return ""
    depth = 1
    for end in range(start + 1, len(mask)):
        depth += (mask[end] == "{") - (mask[end] == "}")
        if depth == 0:
            return source[start + 1:end]
    return ""


def _swift_cases(body: str) -> dict[str, str]:
    mask = _swift_mask(body)
    starts = []
    for match in re.finditer(r"^\s*(case\s+[^:]+:|default:)", body, re.MULTILINE):
        prefix = mask[:match.start()]
        if prefix.count("{") == prefix.count("}"):
            starts.append(match)
    result = {}
    for index, match in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(body)
        names = re.findall(r"\.([A-Za-z][A-Za-z0-9_]*)", match.group()) or ["default"]
        for name in names:
            result[name] = body[match.end():end]
    return result


def _fixture_registry_types(source: str, raw_to_case: dict[str, str]) -> set[str]:
    # Literal records and typed helper calls both create real gallery fixtures;
    # their IDs need not be the registry key's spelling.
    source = _swift_without_comments(source)
    literals = set(re.findall(r'\btype:\s*"([^"]+)"', source))
    cases = set(re.findall(r"\b(?:type|childType):\s*(?:EmbedType)?\.([A-Za-z][A-Za-z0-9_]*)", source))
    return literals | {raw for raw, case in raw_to_case.items() if case in cases}


