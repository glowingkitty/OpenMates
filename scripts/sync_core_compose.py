#!/usr/bin/env python3
"""Generate core Compose files from the self-host source and source-mode overrides."""

import argparse
from pathlib import Path

import yaml

if __package__:
    from . import sync_rust_cli_assets
else:
    import sync_rust_cli_assets

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path("backend/core/docker-compose.selfhost.yml")
DEV_OVERRIDES = Path("backend/core/core-compose.dev-overrides.yml")
DEV_COMPOSE = Path("backend/core/docker-compose.yml")
NPM_COMPOSE = sync_rust_cli_assets.TEMPLATES / "core/docker-compose.selfhost.yml"
HEADER = "# Generated by scripts/sync_core_compose.py. Edit backend/core/docker-compose.selfhost.yml"
QUEUE_TOKEN = "@canonical-celery-queues@"


class ComposeDumper(yaml.SafeDumper):
    """Keep shell commands readable and list indentation compatible with Compose files."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _string(dumper, text):
    style = "|" if "\n" in text else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", text, style=style)


ComposeDumper.add_representer(str, _string)


def _apply_overrides(base, overrides, path=()):
    result = dict(base)
    for key, value in overrides.items():
        if value is None:
            if key not in result:
                raise ValueError(f"Stale removal in dev overrides: {'.'.join((*path, key))}")
            del result[key]
        elif isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = _apply_overrides(result[key], value, (*path, key))
        else:
            result[key] = value
    return result


def render_dev(source: str, override_text: str) -> str:
    """Apply source-build differences, retaining canonical service membership and queues."""
    compose = yaml.safe_load(source)
    overrides = yaml.safe_load(override_text)
    services = compose["services"]
    changed_services = overrides.get("services", {})
    if unknown := changed_services.keys() - services.keys():
        raise ValueError(f"Dev overrides reference unknown core services: {sorted(unknown)}")
    # Compose x-fields express self-host YAML anchors. PyYAML already resolved them.
    base = {key: value for key, value in compose.items() if not key.startswith("x-")}
    dev = _apply_overrides(base, overrides)
    if dev["services"].keys() != services.keys():
        raise ValueError("Dev overrides must retain the canonical core service set")

    for service, config in dev["services"].items():
        canonical = services[service]
        queues = canonical.get("environment", {}).get("CELERY_QUEUES")
        if queues and "command" in changed_services.get(service, {}):
            command = config["command"]
            if not isinstance(command, list) or sum(arg.count(QUEUE_TOKEN) for arg in command) != 1:
                raise ValueError(f"{service}: custom dev worker command must use {QUEUE_TOKEN}")
            config["command"] = [arg.replace(QUEUE_TOKEN, queues) for arg in command]
        if queues and config.get("environment", {}).get("CELERY_QUEUES") != queues:
            raise ValueError(f"{service}: dev must inherit the canonical CELERY_QUEUES")

    return (
        f"{HEADER} and {DEV_OVERRIDES}.\n"
        + yaml.dump(dev, Dumper=ComposeDumper, sort_keys=False, width=120)
    )


def synchronize(root: Path = ROOT, *, check: bool = False) -> None:
    """Write generated manifests or fail if any committed output has drifted."""
    source = (root / SOURCE).read_bytes()
    outputs = {
        DEV_COMPOSE: render_dev(source.decode(), (root / DEV_OVERRIDES).read_text()).encode(),
        NPM_COMPOSE: source,
    }
    stale = []
    for target, expected in outputs.items():
        path = root / target
        if check:
            if path.is_symlink() or not path.is_file() or path.read_bytes() != expected:
                stale.append(str(target))
        else:
            if path.is_symlink():
                raise ValueError(f"Refusing symlink Compose output: {target}")
            path.write_bytes(expected)
    if stale:
        raise ValueError(f"Core Compose drift: {', '.join(stale)}. Run python3 scripts/sync_core_compose.py.")
    sync_rust_cli_assets.synchronize(root, check=check)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        synchronize(check=args.check)
    except (OSError, ValueError, yaml.YAMLError) as error:
        raise SystemExit(str(error)) from error


if __name__ == "__main__":
    main()
