def suggest_entry(root: Path, ref: str) -> dict[str, Any]:
    """Evidence-based stub for a new Specification or app; humans confirm the statuses."""
    specs = discover_specifications(root)
    apps = discover_apps(root)
    if ref.startswith("app:"):
        app_id = ref.removeprefix("app:")
        if app_id not in apps:
            raise FeatureOverviewError(f"unknown app {app_id}")
        entry: dict[str, Any] = {
            "id": app_id.replace("_", "-"), "name": apps[app_id]["name"], "kind": "app",
            "description": apps[app_id]["description"] or "unverified", "specifications": [], "apps": [app_id],
        }
    elif ref in specs:
        spec = specs[ref]
        entry = {
            "id": ref.split(".", 1)[-1].replace(".", "-"), "name": spec["title"],
            "kind": "platform" if ref.startswith("architecture.") else "surface" if ref.startswith("surface.") else "core",
            "description": spec["summary"].split(". ")[0].rstrip(".") + ".", "specifications": [ref], "apps": [],
        }
    else:
        raise FeatureOverviewError(f"unknown Specification or app: {ref}")
    entry["release"] = "unverified"
    entry["surfaces"] = suggest_surfaces(entry, spec_tests(root), required_surfaces(root))
    return entry


def suggest_surfaces(entry: dict[str, Any], tests: dict[str, Any], required: dict[str, set[str]]) -> dict[str, str]:
    """tested when E2E proof exists, implemented with unit proof only, else unverified/not_planned."""
    entry_tests = _entry_tests(entry, tests)
    wanted: set[str] = set()
    for spec_id in entry.get("specifications") or []:
        wanted |= required.get(spec_id, set())
    if "cli" in wanted:
        wanted.add("tui")
    has_specs = bool(entry.get("specifications"))
    statuses: dict[str, str] = {}
    for surface in SURFACES:
        e2e = surface in entry_tests and entry_tests[surface]["e2e"]
        unit = surface in entry_tests and entry_tests[surface]["unit"]
        if surface in OPTIONAL_SURFACES and not (e2e or unit):
            continue
        if e2e:
            statuses[surface] = "tested"
        elif unit:
            statuses[surface] = "implemented"
        elif surface in wanted or not has_specs:
            statuses[surface] = "unverified"
        else:
            statuses[surface] = "not_planned"
    return statuses


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--repo-root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="validate entries and fail on a stale generated view")
    parser.add_argument("--no-drift", action="store_true", help="with --check: skip the generated-view comparison")
    sub = parser.add_subparsers(dest="command")
    suggest = sub.add_parser("suggest", help="print an entry stub for a Specification id or app:<id>")
    suggest.add_argument("ref")
    args = parser.parse_args(argv)
    root = args.repo_root.resolve()
    try:
        if args.command == "suggest":
            print(yaml.safe_dump([suggest_entry(root, args.ref)], sort_keys=False, allow_unicode=True, width=120), end="")
            return 0
        if args.check:
            problems = validate(root)
            if not args.no_drift and not problems:
                problems = drift(root)
            for problem in problems:
                print(f"feature overview: {problem}", file=sys.stderr)
            if problems:
                print(f"Fix {MANUAL}, then run python3 scripts/feature_overview.py (see the file header).", file=sys.stderr)
                return 1
            print("feature overview: ok")
            return 0
        for path in write_outputs(root):
            print(f"updated {path}")
        return 0
    except FeatureOverviewError as exc:
        print(f"feature overview: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
