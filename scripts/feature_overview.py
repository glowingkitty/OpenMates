def validate(root: Path) -> list[str]:
    """Return every problem with the manual file against the current repository."""
    errors: list[str] = []
    try:
        entries = load_manual(root)
    except FeatureOverviewError as exc:
        return [str(exc)]
    specs = discover_specifications(root)
    apps = discover_apps(root)
    products = set(product_feature_ids(root))
    _dev, prod, known_flags = flag_services(root, apps)
    tests = spec_tests(root)
    spec_owner: dict[str, str] = {}
    app_owner: dict[str, str] = {}
    product_refs: set[str] = set()
    ids: set[str] = set()
    for position, entry in enumerate(entries):
        label = f"features[{position}]"
        if not isinstance(entry, dict):
            errors.append(f"{label}: must be a mapping")
            continue
        entry_id = str(entry.get("id") or "")
        label = f"feature '{entry_id or position}'"
        if not ID_RE.match(entry_id):
            errors.append(f"{label}: id must be kebab-case")
        if entry_id in ids:
            errors.append(f"{label}: duplicate id")
        ids.add(entry_id)
        unknown = set(entry) - ENTRY_KEYS
        if unknown:
            errors.append(f"{label}: unknown keys {sorted(unknown)}")
        for field in ("name", "description"):
            if not str(entry.get(field) or "").strip():
                errors.append(f"{label}: {field} is required")
        if entry.get("kind") not in KINDS:
            errors.append(f"{label}: kind must be one of {list(KINDS)}")
        if not RELEASE_RE.match(str(entry.get("release") or "")):
            errors.append(f"{label}: release must be a version tag, untagged-main, unreleased or unverified")
        for spec_id in entry.get("specifications") or []:
            if spec_id not in specs:
                errors.append(f"{label}: Specification '{spec_id}' does not exist")
            elif spec_id in spec_owner:
                errors.append(f"{label}: Specification '{spec_id}' is already listed by '{spec_owner[spec_id]}'")
            spec_owner.setdefault(spec_id, entry_id)
        for app_id in entry.get("apps") or []:
            if app_id not in apps:
                errors.append(f"{label}: app '{app_id}' has no backend/apps/{app_id}/app.yml")
            elif app_id in app_owner:
                errors.append(f"{label}: app '{app_id}' is already listed by '{app_owner[app_id]}'")
            app_owner.setdefault(app_id, entry_id)
        for product_id in entry.get("product_features") or []:
            if product_id not in products:
                errors.append(f"{label}: product feature '{product_id}' is not in {PRODUCT_FEATURES}")
            product_refs.add(product_id)
        for flag in entry.get("flags") or []:
            if flag not in known_flags:
                errors.append(f"{label}: feature flag '{flag}' is not defined (app.yml or PLATFORM_FEATURES)")
        for platform in entry.get("apple_platforms") or []:
            if platform not in APPLE_PLATFORMS:
                errors.append(f"{label}: apple_platforms entry '{platform}' must be one of {list(APPLE_PLATFORMS)}")
        errors.extend(_validate_surfaces(root, entry, label, tests, prod))
    for spec_id in sorted(set(specs) - set(spec_owner)):
        errors.append(f"Specification '{spec_id}' has no entry in {MANUAL} (add one: feature_overview.py suggest {spec_id})")
    for app_id in sorted(set(apps) - set(app_owner)):
        errors.append(f"app '{app_id}' has no entry in {MANUAL} (add one: feature_overview.py suggest app:{app_id})")
    for product_id in sorted(products - product_refs):
        errors.append(f"product feature '{product_id}' ({PRODUCT_FEATURES}) is not linked from any entry")
    return errors


def _validate_surfaces(root: Path, entry: dict[str, Any], label: str, tests: dict[str, Any], prod: Any) -> list[str]:
    errors: list[str] = []
    surfaces = entry.get("surfaces")
    if not isinstance(surfaces, dict):
        return [f"{label}: surfaces must map each surface to a status"]
    for surface in SURFACES:
        if surface not in surfaces and surface not in OPTIONAL_SURFACES:
            errors.append(f"{label}: surface '{surface}' is missing")
    for surface in set(surfaces) - set(SURFACES):
        errors.append(f"{label}: unknown surface '{surface}'")
    key_tests = entry.get("key_tests") or {}
    if not isinstance(key_tests, dict):
        return errors + [f"{label}: key_tests must map surfaces to test paths"]
    for surface, paths in key_tests.items():
        if surface not in SURFACES:
            errors.append(f"{label}: key_tests surface '{surface}' is unknown")
        for path in paths or []:
            if not (root / str(path)).is_file():
                errors.append(f"{label}: key test '{path}' does not exist")
    entry_tests = _entry_tests(entry, tests)
    flags = entry_flag_ids(entry)
    for surface, status in surfaces.items():
        if status not in STATUSES:
            errors.append(f"{label}: {surface} status '{status}' must be one of {list(STATUSES)}")
            continue
        has_tests = bool(key_tests.get(surface)) or (
            surface in entry_tests and any(entry_tests[surface][kind] for kind in ("e2e", "unit"))
        )
        if status in ("tested", "live") and not has_tests:
            errors.append(f"{label}: {surface} is '{status}' but no test proves it (link a Specification test or add key_tests)")
        if status == "live":
            base = [flag for flag in flags if not flag.startswith("skill:")] or flags[:1]
            required = [*base, *SURFACE_PLATFORM_FLAGS.get(surface, ())]
            disabled = [flag for flag in required if not prod.is_enabled(flag)]
            if _flag_state(prod, flags) == "disabled" or disabled:
                errors.append(f"{label}: {surface} is 'live' but disabled in production config: {disabled}")
            if entry.get("release") == "unreleased":
                errors.append(f"{label}: {surface} is 'live' but release is 'unreleased'")
    return errors


