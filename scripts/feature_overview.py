MANUAL = Path("specifications/features.yml")
GENERATED_YML = Path("specifications/generated/features.yml")
GENERATED_MD = Path("specifications/generated/features.md")
GENERATED_PATHS = (str(GENERATED_YML), str(GENERATED_MD))
