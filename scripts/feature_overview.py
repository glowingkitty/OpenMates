APPS_DIR = Path("backend/apps")
APP_I18N = Path("frontend/packages/ui/src/i18n/sources/apps.yml")
PROD_CONFIG = Path("backend/config/backend_config.yml")
DEV_CONFIG = Path("backend/config/backend_config.dev.yml")
HEADER = (
    "# GENERATED by scripts/feature_overview.py from specifications/features.yml and committed sources.\n"
    "# Do not edit by hand. Refresh: python3 scripts/feature_overview.py   Verify: --check\n"
)

SURFACES = ("web", "apple", "watchos", "cli", "tui", "rest_api", "sdk_npm", "sdk_pypi")
OPTIONAL_SURFACES = frozenset({"watchos"})
SURFACE_LABELS = {
    "web": "Web", "apple": "Apple", "watchos": "Watch", "cli": "CLI", "tui": "TUI",
    "rest_api": "REST API", "sdk_npm": "npm SDK", "sdk_pypi": "PyPI SDK",
}
STATUSES = ("not_planned", "planned", "in_progress", "implemented", "tested", "live", "unverified")
STATUS_SHORT = {
    "not_planned": "—", "planned": "planned", "in_progress": "wip", "implemented": "impl",
    "tested": "tested", "live": "**live**", "unverified": "?",
}
KINDS = ("core", "app", "apple", "platform", "internal", "surface")
APPLE_PLATFORMS = ("ios", "ipados", "macos")
RELEASE_RE = re.compile(r"^(v\d+\.\d+(\.\d+)?(-[0-9A-Za-z.-]+)?|untagged-main|unreleased|unverified)$")
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
ENTRY_KEYS = {
    "id", "name", "description", "kind", "specifications", "apps", "flags", "product_features",
    "release", "surfaces", "apple_platforms", "key_tests", "notes",
}
# Assertion-index surface tags -> overview surfaces (path rules in classify_test refine these).
TAG_SURFACES = {
    "gui.web": "web", "gui.apple": "apple", "cli": "cli", "rest_api": "rest_api",
    "sdks.npm": "sdk_npm", "sdks.pip": "sdk_pypi",
}
# A surface may only be "live" when its platform flag is on in production.
SURFACE_PLATFORM_FLAGS = {"apple": ("platform:ios",), "watchos": ("platform:apple-watch",)}
KEY_UNIT_LIMIT = 5
# Flag states: enabled, partial (the app is on, some of its gated skills are off), no_flag (ungated), disabled.
ON_STATES = ("enabled", "partial", "no_flag")
FLAG_LABELS = {"enabled": "on", "partial": "partly on", "no_flag": "on (no flag)", "disabled": "off"}


_LOADER = getattr(yaml, "CSafeLoader", yaml.SafeLoader)


class FeatureOverviewError(Exception):
    """Unreadable or malformed input."""


def _load_yaml(path: Path) -> Any:
    try:
        return yaml.load(path.read_text(encoding="utf-8"), Loader=_LOADER)
    except FileNotFoundError as exc:
        raise FeatureOverviewError(f"missing input: {path}") from exc
    except yaml.YAMLError as exc:
        raise FeatureOverviewError(f"invalid YAML in {path}: {exc}") from exc


def is_feature_overview_input(path: str) -> bool:
    """Return True when a repo-relative path can change the overview or its checks."""
    return (
        path.startswith("specifications/")
        or path == "scripts/feature_overview.py"
        or path in (str(PRODUCT_FEATURES), str(APP_I18N), str(PROD_CONFIG), str(DEV_CONFIG))
        or (path.startswith("backend/apps/") and path.endswith("/app.yml"))
        or "/tests/" in path or "Tests/" in path
    )


# --------------------------------------------------------------------------- sources


def discover_specifications(root: Path) -> dict[str, dict[str, Any]]:
    """Every Specification bundle on disk: id -> status, title, summary, path."""
    specs: dict[str, dict[str, Any]] = {}
    for base in SPEC_DIRS:
        for path in sorted((root / base).glob("**/specification.yml")):
            data = _load_yaml(path) or {}
            spec_id = str(data.get("id") or "")
            if not spec_id:
                raise FeatureOverviewError(f"{path.relative_to(root)} has no id")
            specs[spec_id] = {
                "status": str(data.get("status") or "unknown"),
                "title": str(data.get("title") or spec_id),
                "summary": " ".join(str(data.get("summary") or "").split()),
                "path": str(path.parent.relative_to(root)),
            }
    return specs


def discover_apps(root: Path) -> dict[str, dict[str, Any]]:
    """Every backend app with an app.yml: id -> name, description, raw config."""
    i18n_path = root / APP_I18N
    i18n = (_load_yaml(i18n_path) or {}) if i18n_path.exists() else {}
    apps: dict[str, dict[str, Any]] = {}
    for path in sorted((root / APPS_DIR).glob("*/app.yml")):
        app_id = path.parent.name
        raw = _load_yaml(path) or {}
        name_key = str(raw.get("name_translation_key") or f"apps.{app_id}").removeprefix("apps.")
        desc_key = str(raw.get("description_translation_key") or f"apps.{app_id}.description").removeprefix("apps.")
        apps[app_id] = {
            "name": str((i18n.get(name_key) or {}).get("en") or app_id),
            "description": str((i18n.get(desc_key) or {}).get("en") or ""),
            "raw": raw,
            "source": str(path.relative_to(root)),
        }
    return apps


def product_feature_ids(root: Path) -> list[str]:
    data = _load_yaml(root / PRODUCT_FEATURES) or {}
    return [str(item["id"]) for item in data.get("features") or [] if isinstance(item, dict) and item.get("id")]


def _availability_module(root: Path):
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))
    return importlib.import_module("backend.core.api.app.services.feature_availability_service")


def flag_services(root: Path, apps: dict[str, dict[str, Any]]) -> tuple[Any, Any, set[str]]:
    """Return (dev service, prod service, known feature ids) built from committed config."""
    module = _availability_module(root)
    definitions = list(module.PLATFORM_FEATURES)
    for app_id, app in apps.items():
        definitions.extend(module.collect_feature_definitions_from_app_config(app_id, app["raw"], source=app["source"]))
    known = {definition.id for definition in definitions}
    dev = module.FeatureAvailabilityService(definitions, _load_yaml(root / DEV_CONFIG) or {})
    prod = module.FeatureAvailabilityService(definitions, _load_yaml(root / PROD_CONFIG) or {})
    return dev, prod, known


def classify_test(path: str, tag: str | None) -> tuple[str, str] | None:
    """Map one test file to (surface, "e2e" | "unit"), or None when it proves no product surface."""
    name = path.rsplit("/", 1)[-1]
    if path.startswith("apple/"):
        top = path.split("/")[1] if "/" in path else ""
        surface = "watchos" if "Watch" in top or name.startswith("Watch") else "apple"
        return surface, ("e2e" if "UITests" in top else "unit")
    if path.startswith("frontend/apps/web_app/tests/") and name.endswith(".spec.ts"):
        if name.startswith("cli-tui-") or "-tui-" in name or name.startswith("tui-"):
            return "tui", "e2e"
        if name.startswith("cli-"):
            return "cli", "e2e"
        surface = TAG_SURFACES.get(tag or "")
        return (surface, "e2e") if surface else None
    if "openmates-tui" in path or "/tui/" in path:
        return "tui", "unit"
    if path.startswith("frontend/packages/openmates-cli/"):
        return ("sdk_npm" if tag == "sdks.npm" else "cli"), "unit"
    if path.startswith("packages/openmates-python/"):
        return "sdk_pypi", "unit"
    surface = TAG_SURFACES.get(tag or "")
    return (surface, "unit") if surface else None


@functools.lru_cache(maxsize=4)
def spec_tests(root: Path) -> dict[str, dict[str, dict[str, Counter]]]:
    """spec id -> surface -> kind -> Counter(test path -> assertion hits)."""
    index = (_load_yaml(root / ASSERTION_INDEX) or {}).get("assertions") or {}
    result: dict[str, dict[str, dict[str, Counter]]] = defaultdict(lambda: defaultdict(lambda: defaultdict(Counter)))
    for assertion in index.values():
        spec_id = str(assertion.get("specification") or "").split("@", 1)[0]
        seen: set[str] = set()
        for test in [*(assertion.get("direct_tests") or []), *(assertion.get("supporting_tests") or [])]:
            path = str(test.get("path") or "")
            mapped = classify_test(path, test.get("surface"))
            if not mapped or (path, mapped[0]) in seen:
                continue
            seen.add((path, mapped[0]))
            surface, kind = mapped
            result[spec_id][surface][kind][path] += 1
    return result


def required_surfaces(root: Path) -> dict[str, set[str]]:
    """spec id -> overview surfaces its assertions are required on (registry)."""
    registry_path = root / REGISTRY
    if not registry_path.exists():
        return {}
    specs = (_load_yaml(registry_path) or {}).get("specifications") or {}
    mapped: dict[str, set[str]] = {}
    for spec_id, data in specs.items():
        surfaces = {TAG_SURFACES[tag] for tag in data.get("required_applies_to") or [] if tag in TAG_SURFACES}
        mapped[spec_id] = surfaces
    return mapped


# --------------------------------------------------------------------------- build


def load_manual(root: Path) -> list[dict[str, Any]]:
    data = _load_yaml(root / MANUAL) or {}
    entries = data.get("features")
    if not isinstance(entries, list):
        raise FeatureOverviewError(f"{MANUAL} must contain a 'features' list")
    return entries


def entry_flag_ids(entry: dict[str, Any]) -> list[str]:
    ids = [f"app:{app_id}" for app_id in entry.get("apps") or []]
    ids.extend(str(flag) for flag in entry.get("flags") or [])
    return list(dict.fromkeys(ids))


def _flag_state(service: Any, ids: list[str]) -> str:
    if not ids:
        return "no_flag"
    states = {service.is_enabled(flag) for flag in ids}
    return "enabled" if states == {True} else "disabled" if states == {False} else "partial"


def _entry_tests(entry: dict[str, Any], tests: dict[str, Any]) -> dict[str, dict[str, Counter]]:
    merged: dict[str, dict[str, Counter]] = defaultdict(lambda: defaultdict(Counter))
    for spec_id in entry.get("specifications") or []:
        for surface, kinds in tests.get(spec_id, {}).items():
            for kind, counter in kinds.items():
                merged[surface][kind].update(counter)
    return merged


def build_view(root: Path) -> dict[str, Any]:
    entries = load_manual(root)
    specs = discover_specifications(root)
    apps = discover_apps(root)
    dev, prod, _known = flag_services(root, apps)
    tests = spec_tests(root)
    features: list[dict[str, Any]] = []
    for entry in entries:
        entry_tests = _entry_tests(entry, tests)
        flags = entry_flag_ids(entry)
        key_tests = entry.get("key_tests") or {}
        surfaces: dict[str, Any] = {}
        for surface in SURFACES:
            status = (entry.get("surfaces") or {}).get(surface)
            if status is None and surface in OPTIONAL_SURFACES:
                continue
            e2e = sorted(entry_tests[surface]["e2e"]) if surface in entry_tests else []
            unit_counter = entry_tests[surface]["unit"] if surface in entry_tests else Counter()
            key_unit = [path for path, _ in sorted(unit_counter.items(), key=lambda item: (-item[1], item[0]))[:KEY_UNIT_LIMIT]]
            surfaces[surface] = {
                "status": status,
                "key_tests": list(key_tests.get(surface) or []),
                "e2e_tests": e2e,
                "key_unit_tests": key_unit,
                "unit_test_files": len(unit_counter),
            }
            if surface == "apple":
                surfaces[surface]["platforms"] = list(entry.get("apple_platforms") or APPLE_PLATFORMS)
        features.append({
            "id": entry.get("id"),
            "name": entry.get("name"),
            "kind": entry.get("kind"),
            "description": entry.get("description"),
            "specifications": [
                {"id": spec_id, "status": specs.get(spec_id, {}).get("status", "missing"), "path": specs.get(spec_id, {}).get("path")}
                for spec_id in entry.get("specifications") or []
            ],
            "apps": list(entry.get("apps") or []),
            "product_features": list(entry.get("product_features") or []),
            "release": entry.get("release"),
            "flags": {
                "ids": flags,
                "dev": _flag_state(dev, flags),
                "prod": _flag_state(prod, flags),
            },
            "surfaces": surfaces,
            **({"notes": entry["notes"]} if entry.get("notes") else {}),
        })
    owned_specs = {spec_id for entry in entries for spec_id in entry.get("specifications") or []}
    owned_apps = {app_id for entry in entries for app_id in entry.get("apps") or []}
    return {
        "schema_version": 1,
        "source": str(MANUAL),
        "summary": _summary(features),
        "unmapped": {
            "specifications": sorted(set(specs) - owned_specs),
            "apps": sorted(set(apps) - owned_apps),
        },
        "features": features,
    }


def _summary(features: list[dict[str, Any]]) -> dict[str, Any]:
    per_surface: dict[str, dict[str, int]] = {}
    for surface in SURFACES:
        counts = Counter(f["surfaces"][surface]["status"] for f in features if surface in f["surfaces"])
        per_surface[surface] = {status: counts[status] for status in STATUSES if counts[status]}
    return {
        "features": len(features),
        "enabled_on_prod": sum(1 for f in features if f["flags"]["prod"] in ON_STATES),
        "enabled_on_dev": sum(1 for f in features if f["flags"]["dev"] in ON_STATES),
        "status_by_surface": per_surface,
    }


