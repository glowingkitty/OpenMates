#!/usr/bin/env python3
# contract-test-file: infrastructure
"""Opt-in dev-only real-inference browser proof for the design.embroidery chat flow.

Runs frontend/apps/web_app/tests/design-embroidery-chat.spec.ts against
https://app.dev.openmates.org with the personal dev test account, the installed
Chromium under ~/.cache/ms-playwright and video on. Screenshots, video, the run
log and a receipt land in --output-dir (a fresh path below /tmp).

Example (after deployment; paid inference requires explicit opt-in):
  python3 scripts/design_embroidery_web_real_test.py --session ID --revision FULL_SHA \
    --output-dir /tmp/design-embroidery-web-proof/run-1 \
    --personal-dev-test-account --allow-paid-dev-inference

Never run in CI. The spec deletes its own chat, also on failure.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import threading
import urllib.request
from datetime import UTC, datetime
from pathlib import Path
from uuid import uuid4

from code_run_real_test import ROOT, personal_test_environment
from workflow_schedule_real_test import ProofError, sessions, write_receipt

APP_URL = "https://app.dev.openmates.org"
SPEC = "tests/design-embroidery-chat.spec.ts"
WEB_APP = ROOT / "frontend/apps/web_app"
CANONICAL_NODE_MODULES = Path("/home/superdev/projects/OpenMates/frontend/apps/web_app/node_modules")
CHROMIUM_GLOB = "chromium-*/chrome-linux/chrome"
CONFIG = """// Generated by scripts/design_embroidery_web_real_test.py; proof-only overrides.
const base = require({base}).default;
module.exports = {{
  ...base,
  testDir: {test_dir},
  outputDir: {results},
  retries: 0,
  workers: 1,
  reporter: [['list'], ['json', {{ outputFile: {report} }}]],
  use: {{
    ...base.use,
    video: 'on',
    trace: 'off',
    viewport: {{ width: 1400, height: 1000 }},
    launchOptions: {{ ...base.use.launchOptions, executablePath: {chrome} }},
  }},
}};
"""


def installed_chromium() -> Path:
    found = sorted((Path.home() / ".cache/ms-playwright").glob(CHROMIUM_GLOB))
    if not found:
        raise ProofError("installed_chromium_missing")
    return found[-1]


def acquire_leases(session_id: str, timeout: int) -> list[tuple[str, str, set[str], str]]:
    """Shared dev-stack lease plus the exclusive personal account lease; waits up to ``timeout``."""
    owner, leases = f"repository-session-{session_id}", []
    try:
        for name, resources, mode in (("stack", {sessions.DOCKER_RESOURCE_DEV_STACK}, "shared"),
                                      ("account", {"playwright-account:personal-dev"}, "exclusive")):
            lease_id = f"embroidery-web-{name}-{uuid4().hex[:12]}"
            sessions.acquire_test_resource_lease(lease_id, owner, resources, mode=mode, timeout=timeout)
            leases.append((lease_id, owner, resources, mode))
        return leases
    except BaseException:
        for lease_id, *_ in reversed(leases):
            sessions.release_test_resource_lease(lease_id)
        raise


def require_runtime_revision(revision: str) -> None:
    """The backend runtime checkout serves ``revision``: same commit, or an ancestor with identical backend files.

    A deploy that changes only the web app leaves the runtime checkout on the previous commit.
    """
    checkout = str(sessions.PRODUCT_RUNTIME_CHECKOUT)
    head = subprocess.run(["git", "-C", checkout, "rev-parse", "HEAD"],
                          capture_output=True, text=True, check=False, timeout=10)
    if head.returncode:
        raise ProofError("deployed_runtime_revision_mismatch")
    runtime = head.stdout.strip()
    if runtime == revision:
        return
    for command in (["merge-base", "--is-ancestor", runtime, revision],
                    ["diff", "--quiet", runtime, revision, "--", "backend"]):
        if subprocess.run(["git", "-C", str(ROOT), *command], check=False, timeout=30).returncode:
            raise ProofError("deployed_runtime_revision_mismatch")


def require_frontend_revision(revision: str) -> None:
    with urllib.request.urlopen(f"{APP_URL}/_app/version.json", timeout=20) as response:
        served = json.load(response).get("version")
    if served != revision:
        raise ProofError("frontend_revision_mismatch")


def summarise(out: Path, receipt: dict) -> None:
    """Record media paths and the numbers the spec logged (no credentials are logged)."""
    receipt["screenshots"] = sorted(str(p) for p in (out / "artifacts").glob("*.png"))
    receipt["videos"] = sorted(str(p) for p in (out / "results").rglob("*.webm"))
    log = (out / "run.log").read_text(errors="replace") if (out / "run.log").exists() else ""
    for key, pattern in (("card_numbers", r"card numbers: ([^\n]+)"),
                         ("opened_view", r"opened view size: ([^\n]+)"),
                         ("download", r"downloaded file: ([^\n]+)"),
                         ("models", r"reply generated by: ([^\n]+)")):
        receipt[key] = [m.strip() for m in re.findall(pattern, log)]
    report = out / "report.json"
    if report.exists():
        stats = json.loads(report.read_text()).get("stats", {})
        receipt["playwright_stats"] = {k: stats.get(k) for k in ("expected", "unexpected", "skipped", "flaky")}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--session", required=True)
    parser.add_argument("--revision", required=True, help="Exact deployed dev SHA")
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--personal-dev-test-account", action="store_true", required=True)
    parser.add_argument("--allow-paid-dev-inference", action="store_true")
    parser.add_argument("--timeout-seconds", type=int, default=1500, help="Whole Playwright run")
    parser.add_argument("--lease-timeout-seconds", type=int, default=1800, help="Wait for the account lease")
    args = parser.parse_args()
    if any(os.getenv(key) for key in ("CI", "GITHUB_ACTIONS", "BUILDKITE", "GITLAB_CI")):
        parser.error("real inference is dev-only and cannot run in CI")
    if not args.allow_paid_dev_inference:
        parser.error("explicit paid-dev opt-in required")
    if not re.fullmatch(r"[0-9a-f]{40}", args.revision):
        parser.error("--revision must be the full deployed dev SHA")
    out = args.output_dir.resolve()
    if not out.is_relative_to(Path("/tmp")) or out == Path("/tmp") or out.is_relative_to(ROOT) or out.exists():
        parser.error("--output-dir must be a fresh path below /tmp, outside the repository")

    receipt: dict = {"status": "started", "target": APP_URL, "session": args.session, "spec": SPEC,
                     "deployed_revision": args.revision, "started_at": datetime.now(UTC).isoformat()}
    leases: list = []
    stop, errors = threading.Event(), []
    heartbeat = None
    link = WEB_APP / "node_modules"
    created_link = False
    old_umask = os.umask(0o077)
    try:
        out.mkdir(parents=True)
        (out / "artifacts").mkdir()
        require_frontend_revision(args.revision)
        require_runtime_revision(args.revision)
        env = personal_test_environment()
        for suffix in ("EMAIL", "PASSWORD", "OTP_KEY"):
            env.pop(f"OPENMATES_TEST_ACCOUNT_1_{suffix}", None)
        env.update(PLAYWRIGHT_TEST_BASE_URL=APP_URL, PLAYWRIGHT_VIDEO_MODE="on")
        chrome = installed_chromium()
        if not link.exists():
            link.symlink_to(CANONICAL_NODE_MODULES, target_is_directory=True)
            created_link = True
        config = out / "playwright.proof.config.cjs"
        config.write_text(CONFIG.format(
            base=json.dumps(str(WEB_APP / "playwright.config.ts")), test_dir=json.dumps(str(WEB_APP / "tests")),
            results=json.dumps(str(out / "results")), report=json.dumps(str(out / "report.json")),
            chrome=json.dumps(str(chrome))))
        leases = acquire_leases(args.session, args.lease_timeout_seconds)

        def renew() -> None:
            while not stop.wait(sessions.DOCKER_TEST_LEASE_RENEW_INTERVAL_SECONDS):
                for lease_id, owner, resources, mode in leases:
                    try:
                        sessions.renew_test_resource_lease(lease_id, owner, resources, mode=mode)
                    except RuntimeError:
                        errors.append("lease_renewal_failed")
                        return

        heartbeat = threading.Thread(target=renew, daemon=True)
        heartbeat.start()
        cli = WEB_APP / "node_modules/@playwright/test/cli.js"
        command = [sys.executable, str(ROOT / "scripts/heavy_slot.py"), "run", "--", "node", str(cli), "test",
                   "--config", str(config), "--trace", "off", SPEC]
        with (out / "run.log").open("w") as log:
            run = subprocess.run(command, cwd=out, env=env, stdout=log, stderr=subprocess.STDOUT,
                                 check=False, timeout=args.timeout_seconds)
        receipt["playwright_exit_code"] = run.returncode
        if errors:
            raise ProofError(errors[0])
        require_runtime_revision(args.revision)
        receipt["status"] = "passed" if run.returncode == 0 else "failed"
    except BaseException as exc:
        receipt["status"] = "failed"
        receipt["error_code"] = str(exc) if isinstance(exc, ProofError) else type(exc).__name__
        if isinstance(exc, RuntimeError) and not isinstance(exc, ProofError) and not leases:
            receipt["error_code"] = "lease_unavailable"
    finally:
        stop.set()
        if heartbeat:
            heartbeat.join(timeout=2)
        for lease_id, *_ in reversed(leases):
            try:
                sessions.release_test_resource_lease(lease_id)
            except RuntimeError:
                receipt.setdefault("cleanup", {})["lease"] = "failed"
                receipt["status"] = "failed"
        if created_link:
            link.unlink()
        if out.exists():
            summarise(out, receipt)
        receipt["finished_at"] = datetime.now(UTC).isoformat()
        write_receipt(out / "receipt.json", receipt)
        os.umask(old_umask)
        print(f"Design embroidery web proof {receipt['status']}; receipt: {out / 'receipt.json'}", flush=True)
    return 0 if receipt["status"] == "passed" else 1


if __name__ == "__main__":
    raise SystemExit(main())
