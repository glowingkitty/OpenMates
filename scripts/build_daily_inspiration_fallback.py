#!/usr/bin/env python3
"""Build the small static Daily Inspiration fallback dictionary from i18n YAML."""
from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'frontend/packages/ui/src/i18n/sources/daily_inspiration_fallback.yml'
LANGUAGES = ROOT / 'frontend/packages/ui/src/i18n/languages.json'
OUTPUT = ROOT / 'frontend/packages/ui/src/demo_chats/hardcodedInspirationFallbackText.ts'
CARDS = ('antikythera', 'bioluminescence', 'fermi', 'export', 'pii', 'focus', 'memories', 'events')
FIELDS = ('phrase', 'title', 'description', 'assistant_response')


def build() -> None:
    source = yaml.safe_load(SOURCE.read_text(encoding='utf-8'))
    locales = [entry['code'] for entry in json.loads(LANGUAGES.read_text(encoding='utf-8'))['languages']]
    data: dict[str, dict[str, dict[str, str]]] = {}
    for locale in locales:
        cards: dict[str, dict[str, str]] = {}
        for card in CARDS:
            fields: dict[str, str] = {}
            for field in FIELDS:
                key = f'{card}.{field}'
                value = source[key].get(locale)
                if not isinstance(value, str) or not value.strip():
                    raise ValueError(f'Missing {locale} translation for {key}')
                fields[field] = value
            cards[card] = fields
        data[locale] = cards
    header = (
        '// Generated by scripts/build_daily_inspiration_fallback.py from '\
        'src/i18n/sources/daily_inspiration_fallback.yml. Do not edit by hand.\n'
        'export type FallbackCardKey = '
        + ' | '.join(json.dumps(card) for card in CARDS)
        + ';\n'
        'export interface FallbackCardCopy {\n'
        '  phrase: string;\n  title: string;\n  description: string;\n  assistant_response: string;\n'
        '}\n'
        'export const HARDCODED_INSPIRATION_FALLBACK_TEXT: Record<string, Record<FallbackCardKey, FallbackCardCopy>> = '
    )
    OUTPUT.write_text(header + json.dumps(data, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(f'Built {len(locales)} locale records in {OUTPUT}')


if __name__ == '__main__':
    build()
