#!/usr/bin/env python3
# contract-test-file: infrastructure
"""Opt-in dev-only real voice-call browser proof, no mocks.

Turns each scenario's spoken question into a WAV with ElevenLabs text-to-speech
(inside the dev ``api`` container, Vault-backed credentials, script
backend/scripts/generate_voice_call_speaker_audio.py), then runs
frontend/apps/web_app/tests/voice-call-real.spec.ts against
https://app.dev.openmates.org with the personal dev test account. Chromium plays
the WAV as its microphone; speech-to-text, AI routing, skills, the Mate's speech
and playback are the real dev stack. Screenshots, the Playwright video, the run
log and a receipt land in --output-dir (a fresh path below /tmp). Same harness,
leases and draft guard as scripts/design_embroidery_web_real_test.py.

Example (after deployment; paid inference requires explicit opt-in):
  python3 scripts/voice_call_web_real_test.py --session ID --revision FULL_SHA \\
    --output-dir /tmp/voice-call-real-proof/run-1 \\
    --personal-dev-test-account --allow-paid-dev-inference --scenario black-hole

One scenario per run: Chromium takes the fake-microphone WAV at launch.

Never run in CI.
"""
from __future__ import annotations

import base64
import json
import os
import subprocess
import sys
import tempfile
import wave
from io import BytesIO
from pathlib import Path

from design_embroidery_web_real_test import ROOT, installed_chromium, main

SPEC = "tests/voice-call-real.spec.ts"
GENERATOR = ROOT / "backend/scripts/generate_voice_call_speaker_audio.py"
CAPITAL_SPEECH_FIXTURE = ROOT / "scripts/fixtures/voice-call-capital.flac"
API_CONTAINER = "api"
# Keep in sync with SCENARIOS in the spec (slug -> spoken question).
SCENARIOS = {
    "capital": "What is the capital of France?",
    "production-features": "What is the capital of France?",
    "black-hole": "How does a black hole work? Show me a video example.",
    "memory": "Which employer should I mention in my cover letter? Use my saved job application profile memory.",
    # Two consecutive spoken turns in one call: a short question, a pause long enough for the
    # spoken reply, then the memory question (one WAV, segments joined in order).
    "two-turns-memory": [
        ("What is the capital of France? Please answer in one short sentence.", 45),
        ("Which employer should I mention in my cover letter? Use my saved job application profile memory.", 90),
    ],
    # Needs VOICE_CALL_FORM_PROMPT (the typed form request, kept outside the repository) passed
    # through OPENMATES_HEAVY_REMOTE_ENV.
    "form": "I'm not sure. What would you suggest? Please go with your suggestion.",
}
PATTERNS = (("heard", r"heard: ([^\n]+)"),
            ("highlight", r"highlight steps: ([^\n]+)"),
            ("played_audio", r"played audio: ([^\n]+)"),
            ("call_duration", r"call duration: ([^\n]+)"),
            ("video_results", r"video results: ([^\n]+)"),
            ("models", r"reply generated by: ([^\n]+)"),
            ("memory", r"(memory (?:saved for the voice question|approval included)|saved memory removed)"),
            ("first_turn", r"first turn: ([^\n]+)"),
            ("included_memories", r"included memories ([^\n]+)"),
            ("follow_up_mate", r"follow-up turn mate: ([^\n]+)"),
            ("notifications", r"notifications: ([^\n]+)"),
            ("form", r"form voice reply: ([^\n]+)"))


def take_scenario(argv: list[str]) -> str:
    """Remove ``--scenario SLUG`` from argv (the shared harness does not know it) and return SLUG."""
    if "--scenario" not in argv or argv.index("--scenario") + 1 >= len(argv):
        raise SystemExit(f"--scenario is required: one of {', '.join(SCENARIOS)}")
    at = argv.index("--scenario")
    slug = argv[at + 1]
    if slug not in SCENARIOS:
        raise SystemExit(f"unknown --scenario {slug!r}: one of {', '.join(SCENARIOS)}")
    del argv[at:at + 2]
    return slug


def speak(text: str, tail_seconds: float) -> tuple[bytes, float]:
    """One spoken segment as a WAV (lead-in silence, speech, tail silence) and its spoken seconds."""
    with GENERATOR.open("rb") as script:
        run = subprocess.run(["docker", "exec", "-i", API_CONTAINER, "python", "-", "--text", text,
                              "--tail-seconds", str(tail_seconds)], stdin=script, capture_output=True,
                             check=False, timeout=180)
    if run.returncode:
        raise SystemExit(f"speaker audio generation failed (exit {run.returncode})")
    result = json.loads(run.stdout.decode().strip().splitlines()[-1])
    return base64.b64decode(result["wav_base64"]), result["speech_seconds"]


def generate_speech(directory: Path, slug: str) -> dict[str, float]:
    """Write <slug>.wav for the scenario (segments joined in order); returns its spoken seconds."""
    if slug == "capital":
        # The recurring check exercises the live provider on the reply. Use the
        # same synthetic question each time so fixture setup cannot fail on it.
        subprocess.run(
            ["ffmpeg", "-nostdin", "-loglevel", "error", "-y", "-i", str(CAPITAL_SPEECH_FIXTURE),
             str(directory / "capital.wav")],
            check=True, timeout=30,
        )
        return {slug: 1.81}
    spoken = SCENARIOS[slug]
    segments = [(spoken, 90)] if isinstance(spoken, str) else spoken
    frames, params, seconds = b"", None, 0.0
    for text, tail in segments:
        data, speech_seconds = speak(text, tail)
        with wave.open(BytesIO(data)) as segment:
            params = params or segment.getparams()
            frames += segment.readframes(segment.getnframes())
        seconds += speech_seconds
    out = BytesIO()
    with wave.open(out, "wb") as joined:
        joined.setparams(params)
        joined.writeframes(frames)
    (directory / f"{slug}.wav").write_bytes(out.getvalue())
    return {slug: seconds}


if __name__ == "__main__":
    if any(os.getenv(key) for key in ("CI", "GITHUB_ACTIONS", "BUILDKITE", "GITLAB_CI")):
        raise SystemExit("real inference is dev-only and cannot run in CI")
    if "--allow-paid-dev-inference" not in sys.argv:
        raise SystemExit("explicit paid-dev opt-in required (--allow-paid-dev-inference)")
    scenario = take_scenario(sys.argv)
    speech_dir = Path(tempfile.mkdtemp(prefix="voice-call-real-speech-", dir="/tmp"))
    print(f"speaker audio: {json.dumps(generate_speech(speech_dir, scenario))} in {speech_dir}", flush=True)
    if scenario == "form" and not os.getenv("VOICE_CALL_FORM_PROMPT"):
        raise SystemExit("--scenario form needs VOICE_CALL_FORM_PROMPT (the typed form request)")
    # The Playwright run goes to E2B (heavy_slot): send the spec's env and the speech folder,
    # keeping names and folders the caller already passes.
    remote_env = ["VOICE_CALL_REAL_DEV", "VOICE_CALL_REAL_SPEECH_DIR", "VOICE_CALL_REAL_SCENARIO"]
    if scenario == "form":
        remote_env.append("VOICE_CALL_FORM_PROMPT")
    caller_env = [name for name in os.getenv("OPENMATES_HEAVY_REMOTE_ENV", "").split(",") if name]
    caller_dirs = [name for name in os.getenv("OPENMATES_HEAVY_REMOTE_DIRS", "").split(",") if name]
    os.environ.update(VOICE_CALL_REAL_DEV="1", VOICE_CALL_REAL_SPEECH_DIR=str(speech_dir),
                      VOICE_CALL_REAL_SCENARIO=scenario, OPENMATES_PROOF_CHROME=str(installed_chromium()),
                      OPENMATES_HEAVY_REMOTE_ENV=",".join(dict.fromkeys(caller_env + remote_env)),
                      OPENMATES_HEAVY_REMOTE_DIRS=",".join(dict.fromkeys(caller_dirs + [str(speech_dir)])))
    raise SystemExit(main(spec=SPEC, title=f"Voice call ({scenario})", doc=__doc__, patterns=PATTERNS))
