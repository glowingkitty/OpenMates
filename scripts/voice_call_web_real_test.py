#!/usr/bin/env python3
# contract-test-file: infrastructure
"""Opt-in dev-only real voice-call browser proof, no mocks.

Turns each scenario's spoken question into a WAV with ElevenLabs text-to-speech
(inside the dev ``api`` container, Vault-backed credentials, script
backend/scripts/generate_voice_call_speaker_audio.py), then runs
frontend/apps/web_app/tests/voice-call-real.spec.ts against
https://app.dev.openmates.org with the personal dev test account. Chromium plays
the WAV as its microphone; speech-to-text, AI routing, skills, the Mate's speech
and playback are the real dev stack. Screenshots, the Playwright video, the run
log and a receipt land in --output-dir (a fresh path below /tmp). Same harness,
leases and draft guard as scripts/design_embroidery_web_real_test.py.

Example (after deployment; paid inference requires explicit opt-in):
  python3 scripts/voice_call_web_real_test.py --session ID --revision FULL_SHA \\
    --output-dir /tmp/voice-call-real-proof/run-1 \\
    --personal-dev-test-account --allow-paid-dev-inference [--grep black-hole]

Never run in CI.
"""
from __future__ import annotations

import base64
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

from design_embroidery_web_real_test import ROOT, installed_chromium, main

SPEC = "tests/voice-call-real.spec.ts"
GENERATOR = ROOT / "backend/scripts/generate_voice_call_speaker_audio.py"
API_CONTAINER = "api"
# Keep in sync with SCENARIOS in the spec (slug -> spoken question).
SCENARIOS = {
    "capital": "What is the capital of France?",
    "black-hole": "How does a black hole work? Show me a video example.",
}
PATTERNS = (("heard", r"heard: ([^\n]+)"),
            ("highlight", r"highlight steps: ([^\n]+)"),
            ("played_audio", r"played audio: ([^\n]+)"),
            ("call_duration", r"call duration: ([^\n]+)"),
            ("video_results", r"video results: ([^\n]+)"),
            ("models", r"reply generated by: ([^\n]+)"),
            ("notifications", r"notifications: ([^\n]+)"))


def generate_speech(directory: Path) -> dict[str, float]:
    """Write <slug>.wav for every scenario; returns the spoken seconds per scenario."""
    seconds: dict[str, float] = {}
    for slug, question in SCENARIOS.items():
        with GENERATOR.open("rb") as script:
            run = subprocess.run(["docker", "exec", "-i", API_CONTAINER, "python", "-", "--text", question,
                                  "--tail-seconds", "90"], stdin=script, capture_output=True, check=False, timeout=180)
        if run.returncode:
            raise SystemExit(f"speaker audio generation failed for {slug} (exit {run.returncode})")
        result = json.loads(run.stdout.decode().strip().splitlines()[-1])
        (directory / f"{slug}.wav").write_bytes(base64.b64decode(result["wav_base64"]))
        seconds[slug] = result["speech_seconds"]
    return seconds


if __name__ == "__main__":
    if any(os.getenv(key) for key in ("CI", "GITHUB_ACTIONS", "BUILDKITE", "GITLAB_CI")):
        raise SystemExit("real inference is dev-only and cannot run in CI")
    if "--allow-paid-dev-inference" not in sys.argv:
        raise SystemExit("explicit paid-dev opt-in required (--allow-paid-dev-inference)")
    speech_dir = Path(tempfile.mkdtemp(prefix="voice-call-real-speech-", dir="/tmp"))
    print(f"speaker audio: {json.dumps(generate_speech(speech_dir))} in {speech_dir}", flush=True)
    os.environ.update(VOICE_CALL_REAL_DEV="1", VOICE_CALL_REAL_SPEECH_DIR=str(speech_dir),
                      OPENMATES_PROOF_CHROME=str(installed_chromium()))
    raise SystemExit(main(spec=SPEC, title="Voice call", doc=__doc__, grep_option=True, patterns=PATTERNS))
