#!/usr/bin/env python3
"""Generate and validate the structured Rust migration status under docs/migration/rust/.

Deterministic and offline: counts are derived from config/sdk-capabilities.json,
config/cli-command-catalog.json and the shared Worker unit sources (reusing the
parsers of generate_rust_migration_status.py). No timestamps are written.

  python3 scripts/rust_migration_yaml.py          # rewrite overview.yml and sub-files
  python3 scripts/rust_migration_yaml.py --check  # fail on drift, schema or consistency errors

performance-history.yml, web-lanes.yml and web-app-curated.yml are hand/agent-curated inputs: they
are validated here, never rewritten.

Architecture: docs/architecture/platforms/rust-migration-status.md
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_rust_migration_status as legacy  # noqa: E402
import rust_perf_history as perf  # noqa: E402

ROOT = legacy.ROOT
DIR = Path("docs/migration/rust")
SCHEMA_VERSION = 1
CURATED = DIR / "web-app-curated.yml"
LANES = DIR / "web-lanes.yml"
LANE_STATUSES = ("planned", "running", "landed")
GENERATED = ("overview.yml", "web-app.yml", "shared-client.yml", "cli.yml", "sdk.yml")
HEADER = "# GENERATED by scripts/rust_migration_yaml.py from committed sources. Do not edit by hand.\n# Refresh: python3 scripts/rust_migration_yaml.py   Verify: --check\n"
OPERATIONS = "operations"
PRIORITY = {"web_app": 1, "shared_client": 1, "cli": 2, "sdk_rust": 3, "sdk_npm": 3, "sdk_python": 3}
ORDER = ("web_app", "shared_client", "cli", "sdk_rust", "sdk_npm", "sdk_python")
FILES = {"web_app": "web-app.yml", "shared_client": "shared-client.yml", "cli": "cli.yml",
         "sdk_rust": "sdk.yml", "sdk_npm": "sdk.yml", "sdk_python": "sdk.yml"}
TITLES = {"web_app": "Web app (shared Rust core Worker units)", "shared_client": "Shared client-side code (Rust, non-operation SDK capabilities)",
          "cli": "CLI (native Rust, command catalog)", "sdk_rust": "Rust SDK (operation capabilities)",
          "sdk_npm": "npm SDK (operation capabilities)", "sdk_python": "Python SDK (operation capabilities)"}
UNITS = {"web_app": "Worker namespaces", "shared_client": "capabilities", "cli": "CLI commands",
         "sdk_rust": "capabilities", "sdk_npm": "capabilities", "sdk_python": "capabilities"}
DONE = {"web_app": "installer registered for the namespace",
        "shared_client": "Rust capability status implemented (domains other than operations)",
        "cli": "command is differential-verified against the npm CLI",
        "sdk_rust": "capability status implemented in Rust (domain operations)",
        "sdk_npm": "capability status implemented in npm (domain operations)",
        "sdk_python": "capability status implemented in Python (domain operations)"}
FORMULA = "percent = round(100 * done / total, 1); done+partial+missing == total; percent says how much is verified-complete, not how much code exists."
BLOCKING_VERDICTS = ("rust_worse", "inconclusive")


def counts(total: int, done: int, partial: int, missing: int) -> dict:
    return {"total": total, "done": done, "partial": partial, "missing": missing,
            "percent": round(100 * done / total, 1) if total else 0.0}


# --- builders -------------------------------------------------------------------


def sdk_entry(cap: dict) -> dict:
    row = {"id": cap["id"], "domain": cap["domain"], "has_fixture": "fixture" in cap}
    for lang in ("rust", "npm", "python"):
        e = cap["languages"][lang]
        row[lang] = {"status": e["status"], "api_symbols": len(e["api"]), "conformance": bool(e["conformance"]), "gaps": len(e["gaps"])}
    return row


def sdk_counts(entries: list[dict], lang: str) -> dict:
    statuses = Counter(e[lang]["status"] for e in entries)
    return counts(len(entries), statuses.get("implemented", 0), statuses.get("partial", 0), statuses.get("missing", 0))


def split_sdk() -> tuple[list[dict], list[dict]]:
    data = legacy.load_json(legacy.SDK_CAPABILITIES)
    entries = sorted((sdk_entry(c) for c in data["capabilities"]), key=lambda e: (e["domain"], e["id"]))
    return [e for e in entries if e["domain"] != OPERATIONS], [e for e in entries if e["domain"] == OPERATIONS]


def domain_counts(entries: list[dict]) -> list[dict]:
    rows = []
    for domain in sorted({e["domain"] for e in entries}):
        subset = [e for e in entries if e["domain"] == domain]
        rows.append({"domain": domain, **{lang: sdk_counts(subset, lang) for lang in ("rust", "npm", "python")}})
    return rows


def build_shared_client() -> dict:
    entries, _ = split_sdk()
    return {"schema_version": SCHEMA_VERSION, "area": "shared_client",
            "scope": "SDK capabilities outside the operations domain: crypto, auth, recovery/sync, configuration, streaming and errors. These are the client-side primitives the web app, CLI and Apple apps share through the Rust core.",
            "source": str(legacy.SDK_CAPABILITIES), "summary": sdk_counts(entries, "rust"),
            "languages": {lang: sdk_counts(entries, lang) for lang in ("rust", "npm", "python")},
            "domains": domain_counts(entries),
            "shared_vector_files": sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "packages/openmates-rust").rglob("*vectors*.json")),
            "capabilities": entries}


def build_sdk() -> dict:
    _, entries = split_sdk()
    return {"schema_version": SCHEMA_VERSION, "area": "sdk",
            "scope": "SDK capabilities in the operations domain (public API operations), counted per language. Priority 3.",
            "source": str(legacy.SDK_CAPABILITIES),
            "summaries": {f"sdk_{lang}": sdk_counts(entries, lang) for lang in ("rust", "npm", "python")},
            "domains": domain_counts(entries), "capabilities": entries}


def is_differential(command: dict) -> bool:
    return any(g.startswith(legacy.DIFFERENTIAL_PREFIX) for g in command["gaps"])


def build_cli() -> dict:
    catalog = legacy.load_json(legacy.CLI_CATALOG)
    commands = catalog["commands"]
    diff = [c for c in commands if is_differential(c)]
    unsupported_open = [c for c in commands if c["implementation"]["status"] == "unsupported" and not is_differential(c)]
    groups: dict[str, list[dict]] = defaultdict(list)
    for c in commands:
        groups[c["path"][0]].append(c)
    rows = []
    for name, members in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        st = Counter(m["implementation"]["status"] for m in members)
        rows.append({"group": name, "commands": len(members), "implemented": st.get("implemented", 0), "partial": st.get("partial", 0),
                     "unsupported": st.get("unsupported", 0), "differential_verified": sum(1 for m in members if is_differential(m)),
                     "linux_verified": sum(1 for m in members if m["platforms"]["linux"] == "verified"),
                     "macos_verified": sum(1 for m in members if m["platforms"]["macos"] == "verified")})
    st = Counter(c["implementation"]["status"] for c in commands)
    total = len(commands)
    return {"schema_version": SCHEMA_VERSION, "area": "cli", "source": str(legacy.CLI_CATALOG), "typescript_cli_version": catalog["source_version"],
            "summary": counts(total, len(diff), total - len(diff) - len(unsupported_open), len(unsupported_open)),
            "status_counts": {"implemented": st.get("implemented", 0), "partial": st.get("partial", 0), "unsupported": st.get("unsupported", 0)},
            "with_native_handler": sum(1 for c in commands if c["implementation"].get("handler")),
            "with_e2e_evidence": sum(1 for c in commands if c.get("evidence")),
            "platforms_verified": {os_name: sum(1 for c in commands if c["platforms"][os_name] == "verified") for os_name in ("linux", "macos", "windows")},
            "groups": rows}


def load_curated() -> dict:
    return yaml.safe_load((ROOT / CURATED).read_text(encoding="utf-8"))["units"]


def load_lanes() -> dict:
    return yaml.safe_load((ROOT / LANES).read_text(encoding="utf-8"))


def lane_summary(lanes: dict) -> dict:
    """Short, derived lane section embedded in web-app.yml."""
    every = lanes["wave3_lanes"] + lanes["lanes"]
    by_status = Counter(lane["status"] for lane in every)
    return {"file": "web-lanes.yml", "plan": "web-lanes.md", "plan_date": lanes["plan_date"], "total": len(every),
            "by_status": {k: by_status.get(k, 0) for k in LANE_STATUSES},
            "landed": [{"name": lane["name"], "commit": lane["commit"]} for lane in every if lane["status"] == "landed"],
            "running": [lane["name"] for lane in every if lane["status"] == "running"],
            "next_planned_by_rank": [lane["name"] for lane in sorted(lanes["lanes"], key=lambda lane: lane["rank"]) if lane["status"] == "planned"][:5]}


def validate_lanes(lanes: dict) -> list[str]:
    errors = []
    if lanes.get("schema_version") != SCHEMA_VERSION:
        errors.append("web-lanes.yml: schema_version mismatch")
    wave4, wave3 = lanes["lanes"], lanes["wave3_lanes"]
    names = [lane["name"] for lane in wave3 + wave4]
    if len(set(names)) != len(names):
        errors.append("web-lanes.yml: lane names must be unique")
    if [lane["rank"] for lane in wave4] != list(range(1, len(wave4) + 1)):
        errors.append("web-lanes.yml: wave4 lanes must be listed in rank order 1..N")
    slices = {f"{lane['name']}-{sl['id']}" for lane in wave4 for sl in lane.get("slices", [])}
    for lane in wave3 + wave4:
        label = f"web-lanes.yml lane {lane['name']}"
        if lane.get("status") not in LANE_STATUSES:
            errors.append(f"{label}: status must be one of {LANE_STATUSES}")
        commit = lane.get("commit")
        if lane.get("status") == "landed" and not (isinstance(commit, str) and re.fullmatch(r"[0-9a-f]{7,40}", commit)):
            errors.append(f"{label}: landed lanes must name a commit")
        if lane.get("status") != "landed" and commit is not None:
            errors.append(f"{label}: only landed lanes carry a commit")
        for dep in lane.get("deps", []) + lane.get("soft_deps", []):
            if dep not in names and dep not in slices:
                errors.append(f"{label}: unknown dependency {dep}")
    return errors


def build_web_app() -> dict:
    installers = legacy.parse_installers((ROOT / legacy.UNIT_REGISTRY).read_text(encoding="utf-8"))
    protocol = (ROOT / legacy.UNIT_PROTOCOL).read_text(encoding="utf-8")
    namespaces = re.findall(r"'(\w+)'", re.search(r"SHARED_NAMESPACES = \[(.*?)\]", protocol, re.S).group(1))
    pre_bind = set(re.findall(r"'(\w+)'", re.search(r"PRE_BIND_NAMESPACES.*?\[(.*?)\]", protocol, re.S).group(1)))
    curated = load_curated()
    units = []
    for ns in namespaces:
        installer = installers.get(ns)
        item = {"namespace": ns, "status": "installed" if installer else "planned", "pre_bind": ns in pre_bind,
                "installer": installer.as_posix() if installer else None}
        if installer:
            item["what_moved"] = legacy.header_summary(installer)
            item["typescript_fallback"] = legacy.fallback_state(installer.parent)
            item["unit_tests"] = [Path(t).name for t in legacy.unit_tests(installer.parent, installer)]
        else:
            item.update({"what_moved": "Planned; no installer yet.", "typescript_fallback": None, "unit_tests": []})
        extra = curated.get(ns, {"specs": [], "vectors": [], "open_gaps": []})
        item.update({"e2e_specs": extra["specs"], "vectors": extra["vectors"], "open_gaps": extra["open_gaps"]})
        units.append(item)
    installed = sum(1 for u in units if u["status"] == "installed")
    specs = sorted(p.name for p in (ROOT / legacy.WEB_SPECS).glob("web-rust-core-*.spec.ts"))
    return {"schema_version": SCHEMA_VERSION, "area": "web_app",
            "sources": [str(legacy.UNIT_REGISTRY), str(legacy.UNIT_PROTOCOL), str(CURATED), str(LANES)],
            "flag": {"env": "VITE_OPENMATES_RUST_CORE", "default": "off", "flag_off_behavior": "original TypeScript path, byte-identical build output (guarded in CI)"},
            "summary": counts(len(units), installed, 0, len(units) - installed),
            "e2e_specs_in_repo": specs, "lanes": lane_summary(load_lanes()), "units": units}


# --- overview + blockers ------------------------------------------------------------


def perf_blockers(history: dict) -> list[str]:
    out = []
    for flow, entry in sorted(perf.latest_by_flow(history).items()):
        if entry["verdict"] in BLOCKING_VERDICTS:
            out.append(f"perf gate not cleared: {flow} is {entry['verdict']} ({entry['id']})")
    return out


def build_overview(files: dict[str, dict], history: dict) -> dict:
    web, shared, cli, sdk = files["web-app.yml"], files["shared-client.yml"], files["cli.yml"], files["sdk.yml"]
    summaries = {"web_app": web["summary"], "shared_client": shared["summary"], "cli": cli["summary"], **sdk["summaries"]}
    planned = [u["namespace"] for u in web["units"] if u["status"] == "planned"]
    blockers = {
        "web_app": ([f"planned units without installer: {', '.join(planned)}"] if planned else []) + perf_blockers(history),
        "shared_client": [f"{s['missing']} capabilities missing in Rust"] if (s := shared["summary"])["missing"] else [],
        "cli": [f"{cli['summary']['missing']} unsupported commands without native handler",
                f"{cli['summary']['total'] - cli['platforms_verified']['linux']} commands not verified on Linux"],
        "sdk_rust": [], "sdk_npm": [], "sdk_python": [],
    }
    for key in ("sdk_rust", "sdk_npm", "sdk_python"):
        if summaries[key]["missing"]:
            blockers[key].append(f"{summaries[key]['missing']} capabilities missing")
    areas = []
    for area in ORDER:
        areas.append({"id": area, "title": TITLES[area], "priority_rank": PRIORITY[area], "file": FILES[area], "unit": UNITS[area],
                      **summaries[area], "done_definition": DONE[area], "blockers": blockers[area]})
    return {"schema_version": SCHEMA_VERSION,
            "description": "Machine-readable Rust migration status. Priority: 1 web app + shared client code, 2 CLI, 3 SDKs. Sub-files hold the detail; performance-history.yml is the append-only measurement log.",
            "formula": FORMULA, "priority_order": list(ORDER), "performance_history": "performance-history.yml",
            "areas": areas}


def build_all() -> dict[str, dict]:
    files = {"web-app.yml": build_web_app(), "shared-client.yml": build_shared_client(), "cli.yml": build_cli(), "sdk.yml": build_sdk()}
    files["overview.yml"] = build_overview(files, perf.load())
    return files


def dump(data: dict) -> str:
    return HEADER + yaml.dump(data, Dumper=perf._EntryDumper, sort_keys=False, width=110, allow_unicode=True)


# --- validation --------------------------------------------------------------------


def check_counts(label: str, c: dict) -> list[str]:
    errors = []
    if c["done"] + c["partial"] + c["missing"] != c["total"]:
        errors.append(f"{label}: done+partial+missing != total")
    expected = round(100 * c["done"] / c["total"], 1) if c["total"] else 0.0
    if c["percent"] != expected:
        errors.append(f"{label}: percent {c['percent']} != formula {expected}")
    return errors


def validate(files: dict[str, dict]) -> list[str]:
    """Schema, ordering and overview-equals-sub-files checks on loaded YAML."""
    errors: list[str] = []
    ov = files["overview.yml"]
    if ov.get("schema_version") != SCHEMA_VERSION:
        errors.append("overview: schema_version mismatch")
    areas = ov["areas"]
    if [a["id"] for a in areas] != list(ORDER) or ov["priority_order"] != list(ORDER):
        errors.append("overview: areas must follow priority_order web_app, shared_client, cli, sdk_rust, sdk_npm, sdk_python")
    ranks = [a["priority_rank"] for a in areas]
    if ranks != sorted(ranks) or {a["id"]: a["priority_rank"] for a in areas} != PRIORITY:
        errors.append("overview: priority ranks must be 1,1,2,3,3,3 in order")
    sub = {"web_app": files["web-app.yml"]["summary"], "shared_client": files["shared-client.yml"]["summary"],
           "cli": files["cli.yml"]["summary"], **files["sdk.yml"]["summaries"]}
    for area in areas:
        keys = ("total", "done", "partial", "missing", "percent")
        label = f"overview {area['id']}"
        errors += check_counts(label, area)
        if {k: area[k] for k in keys} != {k: sub[area["id"]][k] for k in keys}:
            errors.append(f"{label}: numbers differ from {area['file']}")
        errors += check_counts(f"{area['file']} {area['id']}", sub[area["id"]])
    web = files["web-app.yml"]
    installed = sum(1 for u in web["units"] if u["status"] == "installed")
    if (web["summary"]["done"], web["summary"]["total"]) != (installed, len(web["units"])):
        errors.append("web-app.yml: summary differs from unit list")
    if any((u["status"] == "installed") != bool(u["installer"]) for u in web["units"]):
        errors.append("web-app.yml: status must match installer presence")
    for unit in web["units"]:
        for path in unit["vectors"]:
            if not (ROOT / path).is_file():
                errors.append(f"web-app.yml {unit['namespace']}: vector file missing: {path}")
        for spec in unit["e2e_specs"]:
            if spec not in web["e2e_specs_in_repo"]:
                errors.append(f"web-app.yml {unit['namespace']}: spec missing: {spec}")
    cli = files["cli.yml"]
    for key in ("commands", "implemented", "partial", "unsupported", "differential_verified", "linux_verified"):
        total = sum(g[key] for g in cli["groups"])
        want = {"commands": cli["summary"]["total"], "differential_verified": cli["summary"]["done"], "linux_verified": cli["platforms_verified"]["linux"],
                **{k: cli["status_counts"][k] for k in ("implemented", "partial", "unsupported")}}[key]
        if total != want:
            errors.append(f"cli.yml: group sum of {key} ({total}) != {want}")
    sizes = [len(c["capabilities"]) for c in (files["shared-client.yml"], files["sdk.yml"])]
    if sizes != [files["shared-client.yml"]["summary"]["total"], files["sdk.yml"]["summaries"]["sdk_rust"]["total"]]:
        errors.append("capability list length differs from summary total")
    for name in ("shared-client.yml", "sdk.yml"):
        keys = [(c["domain"], c["id"]) for c in files[name]["capabilities"]]
        if keys != sorted(keys):
            errors.append(f"{name}: capabilities must be sorted by domain, id")
    curated = load_curated()
    if set(curated) != {u["namespace"] for u in web["units"]}:
        errors.append(f"{CURATED}: namespaces differ from the unit allowlist")
    errors += validate_lanes(load_lanes())
    if web["lanes"] != lane_summary(load_lanes()):
        errors.append("web-app.yml: lanes section differs from web-lanes.yml")
    errors += [f"performance-history.yml: {e}" for e in perf.validate(perf.load())]
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail on drift, schema or consistency errors")
    args = parser.parse_args()
    built = build_all()
    rendered = {name: dump(data) for name, data in built.items()}
    if args.check:
        problems = []
        for name, text in rendered.items():
            path = ROOT / DIR / name
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                problems.append(f"{DIR / name} is stale; run python3 scripts/rust_migration_yaml.py")
        loaded = {n: yaml.safe_load((ROOT / DIR / n).read_text(encoding="utf-8")) for n in GENERATED if (ROOT / DIR / n).is_file()}
        problems += validate(loaded) if len(loaded) == len(GENERATED) else []
        for line in problems:
            print(line, file=sys.stderr)
        return 1 if problems else 0
    for name, text in rendered.items():
        (ROOT / DIR / name).write_text(text, encoding="utf-8")
    problems = validate(built)
    for line in problems:
        print(line, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
