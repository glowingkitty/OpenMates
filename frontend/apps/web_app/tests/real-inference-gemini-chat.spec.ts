/**
 * Real-inference chat in an isolated per-run CI stack (TASK-5616).
 *
 * Runs only in the `real_inference` CI group: the job uses the protected
 * `real-inference` GitHub environment, whose dev-only provider keys reach the
 * run's own throwaway Vault, and the stack can only reach those providers' hosts.
 * No replay marker is sent, so the reply comes from the real provider.
 *   1. A fresh CI account sends an @Gemini-3.8-Flash question.
 *   2. The reply answers it, and the message says Gemini 3.8 Flash generated it.
 * The chat is deleted afterwards.
 */
export {};

const { test, expect } = require('./console-monitor');
const { createSignupLogger, createStepScreenshotter, getTestAccount } = require('./signup-flow-helpers');
const {
	deleteActiveChat,
	focusMessageEditor,
	loginToTestAccount,
	startNewChat
} = require('./helpers/chat-test-helpers');

const QUESTION = 'What is 17 plus 25? Reply with only the number.';

// contract-test: direct surface=gui.web assertions=daily-ai-tests.real.semantic-signal
test('a real Gemini 3.8 Flash reply arrives in an isolated CI stack', async ({ page }: { page: any }, testInfo: any) => {
	test.setTimeout(240_000);
	if (!getTestAccount().email) {
		throw new Error('Real-inference CI requires a provisioned test account.');
	}
	const log = createSignupLogger('REAL_INFERENCE_GEMINI_CHAT');
	const screenshot = createStepScreenshotter(log);
	await loginToTestAccount(page, log, screenshot);
	await startNewChat(page, log);

	const editor = page.getByTestId('message-editor');
	await focusMessageEditor(editor);
	await page.keyboard.insertText('@Gemini-3.8-Flash');
	const dropdown = page.getByTestId('mention-dropdown');
	await expect(dropdown.getByTestId('mention-result-name').filter({ hasText: /Gemini 3\.8 Flash/i }).first()).toBeVisible({
		timeout: 10_000
	});
	await page.keyboard.press('Tab');
	await expect(dropdown).toBeHidden({ timeout: 5_000 });
	await page.keyboard.insertText(` ${QUESTION}`);
	await page.keyboard.press('Escape');
	await page.locator('[data-action="send-message"]').click();
	await expect(page).toHaveURL(/chat-id=[a-zA-Z0-9-]+/, { timeout: 20_000 });

	const assistant = page.getByTestId('message-assistant').last();
	const generatedBy = assistant.getByTestId('generated-by');
	await expect(generatedBy).toBeVisible({ timeout: 180_000 });
	const model = ((await generatedBy.textContent()) || '').trim();
	log(`Generated by: "${model}"`);
	expect(model.toLowerCase()).toContain('gemini 3.8 flash');
	await expect(assistant).toContainText('42', { timeout: 15_000 });
	await expect(assistant).toHaveAttribute('data-streaming', 'false', { timeout: 60_000 });
	await testInfo.attach('01-real-gemini-reply', { body: await page.screenshot(), contentType: 'image/png' });
	await deleteActiveChat(page, log, screenshot, 'real-inference-gemini');
});
