/** Insert the Gemini 3.8 Flash mention through the dropdown, then send the prompt after it. */
async function sendWithGemini(page: any, prompt: string, log: any, screenshot: any, label: string) {
	const editor = page.getByTestId('message-field').last().getByTestId('message-editor');
	await expect(editor).toBeVisible();
	await focusMessageEditor(editor);
	await page.keyboard.insertText(`@${MODEL_QUERY}`);
	const dropdown = page.getByTestId('mention-dropdown');
	await expect(dropdown).toBeVisible({ timeout: 10_000 });
	await expect(dropdown.getByTestId('mention-result-name').filter({ hasText: MODEL_NAME }).first())
		.toBeVisible({ timeout: 10_000 });
	await page.keyboard.press('Tab');
	await expect(dropdown).not.toBeVisible({ timeout: 3000 });
	await sendMessage(page, ` ${prompt}`, log, screenshot, label, { preserveExistingContent: true });
}

/** The newest finished assistant reply must have been generated by Gemini 3.8 Flash. */
async function expectReplyFromGemini(page: any, log: any, timeout: number) {
	await expect(page.getByTestId('typing-indicator')).not.toBeVisible({ timeout });
	const generatedBy = page.getByTestId('message-assistant').last().getByTestId('generated-by');
	await expect(generatedBy).toBeVisible({ timeout: 120_000 });
	await expect(generatedBy).toContainText(MODEL_NAME);
	log(`reply generated by: ${(await generatedBy.textContent())?.trim()}`);
}

/** Save the opened video's bytes (the page fetches its own object or media URL) to artifacts/<name>. */
async function saveVideo(page: any, overlay: any, name: string, log: any) {
	const video = overlay.getByTestId('video-generate-fullscreen-video');
	const base64: string = await video.evaluate(async (element: HTMLVideoElement) => {
		const response = await fetch(element.currentSrc || element.src);
		if (!response.ok) throw new Error(`video fetch failed: ${response.status}`);
		const bytes = new Uint8Array(await response.arrayBuffer());
		let binary = '';
		for (let offset = 0; offset < bytes.length; offset += 0x8000) {
			binary += String.fromCharCode(...bytes.subarray(offset, offset + 0x8000));
		}
		return btoa(binary);
	});
	const buffer = Buffer.from(base64, 'base64');
	expect(buffer.length, `${name} is not empty`).toBeGreaterThan(1000);
	fs.mkdirSync(ARTIFACTS, { recursive: true });
	fs.writeFileSync(path.join(ARTIFACTS, name), buffer);
	log(`saved video: ${name} (${buffer.length} bytes)`);
}

/** Opens the newest finished video card in the chat; returns the fullscreen overlay. */
async function openNewestVideo(page: any) {
	// The card shows a thumbnail with a play button in its centre; pressing it opens the video, which starts playing.
	const overlay = await openFullscreen(page, page.locator(FINISHED_VIDEO_CARD).last());
	const media = overlay.getByTestId('video-generate-fullscreen');
	await expect(media).toBeVisible({ timeout: 30_000 });
	const video = overlay.getByTestId('video-generate-fullscreen-video');
	await expect(video).toBeVisible({ timeout: 60_000 });
	await expect
		.poll(() => video.evaluate((element: HTMLVideoElement) => !element.paused && element.currentTime > 0), { timeout: 60_000 })
		.toBe(true);
	await expect
		.poll(() => video.evaluate((element: HTMLVideoElement) => element.readyState), { timeout: 60_000 })
		.toBeGreaterThanOrEqual(1);
	return overlay;
}

async function closeOverlay(page: any, overlay: any) {
	if (await overlay.isVisible().catch(() => false)) {
		await overlay.getByTestId('embed-minimize').click({ timeout: 5000 }).catch(() => page.keyboard.press('Escape'));
		await expect(overlay).toBeHidden({ timeout: 10_000 }).catch(() => undefined);
	}
}

/** Keep the browser console lines about embeds and versions; written to artifacts/<name> for diagnosis. */
function collectEmbedConsole(page: any, name: string) {
	const lines: string[] = [];
	page.on('console', (message: any) => {
		const text = message.text();
		if (/embed|version|revision/i.test(text) && !/WebSocketService\] (Sending|Received|Determined|Found|Executing)/.test(text)) {
			lines.push(`[${new Date().toISOString()}] [${message.type()}] ${text.slice(0, 600)}`);
		}
	});
	return () => {
		fs.mkdirSync(ARTIFACTS, { recursive: true });
		fs.writeFileSync(path.join(ARTIFACTS, name), lines.join('\n'));
	};
}

/** SHA-256 of the opened video's bytes, read by the page itself. */
async function shownVideoDigest(overlay: any): Promise<string> {
	return overlay.getByTestId('video-generate-fullscreen-video').evaluate(async (element: HTMLVideoElement) => {
		const bytes = await (await fetch(element.currentSrc || element.src)).arrayBuffer();
		const digest = await crypto.subtle.digest('SHA-256', bytes);
		return Array.from(new Uint8Array(digest)).map((byte) => byte.toString(16).padStart(2, '0')).join('');
	});
}

/** Wait for one more finished assistant reply than `repliesBefore`, generated by Gemini 3.8 Flash. */
async function expectNewReplyFromGemini(page: any, repliesBefore: number, log: any, timeout: number) {
	await expect
		.poll(() => page.getByTestId('message-assistant').count(), { timeout })
		.toBeGreaterThan(repliesBefore);
	await expectReplyFromGemini(page, log, timeout);
}

/**
 * Wait until the same video shows its changed version: reopen the newest card until the shown file is
 * another one than `previousDigest` and version 2 is selected in the version history.
 */
async function openChangedVideo(page: any, overlay: any, previousDigest: string, timeout: number, log: any) {
	let current = overlay;
	await expect(async () => {
		if (!(await current.isVisible().catch(() => false))) current = await openNewestVideo(page);
		const digest = await shownVideoDigest(current);
		if (digest === previousDigest) await closeOverlay(page, current);
		expect(digest, 'the changed video replaced the first one').not.toBe(previousDigest);
	}).toPass({ timeout, intervals: [5000, 10_000, 15_000] });
	await expect(current.getByTestId('version-dot-2')).toBeVisible({ timeout: 60_000 });
	await expect(current.getByTestId('video-generate-fullscreen')).toHaveAttribute('data-embed-version', '2', { timeout: 60_000 });
	log('changed video shown as version 2');
	return current;
}

/** While the video is made its request card names the current step. */
async function screenshotProgress(page: any, screenshot: any, name: string, log: any) {
	const step = page.locator('[data-testid="image-generate-request-model"][data-video-stage]:not([data-video-stage=""])').last();
	await expect(step, 'the request card names the current step').toBeVisible({ timeout: 120_000 });
	log(`progress step shown: ${await step.getAttribute('data-video-stage')} / ${(await step.textContent())?.trim()}`);
	await screenshot(page, name, { fullPage: false });
}

/** The card of a running change shows the video being changed, the kind of change and the instruction. */
async function expectChangeCard(page: any, screenshot: any, name: string, change: string, instruction: RegExp, log: any) {
	const label = page.getByTestId('video-generate-request-change').last();
	await expect(label, 'the change card names the kind of change').toBeVisible({ timeout: 180_000 });
	await expect(label).toHaveAttribute('data-change', change);
	const thumbnail = page.getByTestId('video-generate-request-source').last().getByTestId('video-generate-source-thumbnail');
	await expect(thumbnail, 'the change card shows the video being changed').toBeVisible({ timeout: 30_000 });
	expect(await thumbnail.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);
	await expect(page.getByTestId('image-generate-request-prompt').last()).toContainText(instruction);
	log(`change card: ${(await label.textContent())?.trim()}`);
	await screenshot(page, name, { fullPage: false });
}

/** The finished card: a frame of the video with a play button, no player, and the maker named once. */
async function expectFinishedCard(page: any, log: any) {
	const card = page.locator(FINISHED_VIDEO_CARD).last();
	const thumbnail = card.getByTestId('video-generate-thumbnail');
	await expect(thumbnail, 'the card shows a thumbnail from the video').toBeVisible({ timeout: 60_000 });
	expect(await thumbnail.evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);
	await expect(card.getByTestId('video-generate-play')).toBeVisible();
	await expect(card.locator('video')).toHaveCount(0);
	const text = (await card.innerText()).replace(/\s+/g, ' ');
	expect(text.match(/Created by/g)?.length ?? 0, `the maker is named once in: ${text}`).toBe(1);
	expect(text).not.toMatch(/gpt-6\.1-sol|gemini-omni/);
	log(`finished card text: ${text}`);
}

test.describe('videos.generate chat', () => {
	test.beforeEach(() => {
		// The shared dev stack drops and reopens the socket during these long runs; a housekeeping
		// send that meets the closing socket is retried by the client and is not part of the video flow.
		allowConsoleErrorPatterns([/WebSocket changed before message dispatch/]);
	});

	// contract-test: direct surface=gui.web assertions=videos-generate.routing.generative-or-composed,videos-generate.composed.author-writes-composition,videos-generate.progress.shown-while-running,videos-generate.result.video-with-timeline,videos-generate.timeline.below-the-video,videos-generate.change.edit-mode,videos-generate.change.same-video-next-version
	test('composed video from web results, timeline, edit', async ({ page }) => {
		test.setTimeout(2_400_000);
		skipWithoutCredentials(test, TEST_EMAIL, TEST_PASSWORD, TEST_OTP_KEY);
		const log = createSignupLogger('videos-generate-composed');
		const writeEmbedConsole = collectEmbedConsole(page, 'composed-embed-console.log');
		const screenshot = createStepScreenshotter(log, { filenamePrefix: 'videos-generate-composed' });
		attachConsoleListeners(page);
		attachNetworkListeners(page);

		await loginToTestAccount(page, log, screenshot);
		await startNewChat(page, log);
		let overlay = page.getByTestId('embed-fullscreen-overlay').last();
		try {
			await sendWithGemini(page, SEARCH_PROMPT, log, screenshot, 'search');
			// The assistant may answer with web, news or image search results; any of them feeds the video.
			await expectReplyFromGemini(page, log, SEARCH_TIMEOUT);
			await screenshot(page, 'web-results-found');

			await sendWithGemini(page, COMPOSED_PROMPT, log, screenshot, 'video');
			await screenshotProgress(page, screenshot, 'video-progress', log);
			await expect(page.locator(FINISHED_VIDEO_CARD).first()).toBeVisible({ timeout: COMPOSED_TIMEOUT });
			await expectReplyFromGemini(page, log, COMPOSED_TIMEOUT);
			await expectFinishedCard(page, log);
			await screenshot(page, 'video-card-finished');

			overlay = await openNewestVideo(page);
			const fullscreen = overlay.getByTestId('video-generate-fullscreen');
			await expect(fullscreen).toHaveAttribute('data-made-by', 'composed');
			const timeline = overlay.getByTestId('video-timeline');
			await expect(timeline).toBeVisible();
			await expect(timeline).toHaveAttribute('data-made-by', 'composed');
			const parts = timeline.getByTestId('video-timeline-part');
			expect(await parts.count()).toBeGreaterThanOrEqual(2);
			log(`timeline parts: ${await parts.count()}`);
			await expect(overlay.getByTestId('video-timeline-extend-start')).toHaveCount(0);
			await expect(overlay.getByTestId('video-timeline-extend-end')).toHaveCount(0);
			await screenshot(page, 'composed-fullscreen-timeline', { fullPage: false });

			await parts.nth(1).click();
			const video = overlay.getByTestId('video-generate-fullscreen-video');
			await expect
				.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime), { timeout: 15_000 })
				.toBeGreaterThan(0);
			await screenshot(page, 'composed-second-part-selected', { fullPage: false });
			await saveVideo(page, overlay, 'composed-v1.mp4', log);
			const firstDigest = await shownVideoDigest(overlay);

			await overlay.getByTestId('video-edit-button').click();
			await expect(overlay.getByTestId('video-edit-hint')).toBeVisible();
			// Select the first part that offers an editable text field.
			const partCount = await parts.count();
			let editedPart = -1;
			let textInput = overlay.locator('[data-testid^="video-edit-text-"]').first();
			for (let index = 0; index < partCount && editedPart < 0; index += 1) {
				await parts.nth(index).click();
				await expect(overlay.getByTestId('video-edit-inspector')).toBeVisible();
				if ((await overlay.locator('[data-testid^="video-edit-text-"]').count()) > 0) {
					editedPart = index;
					textInput = overlay.locator('[data-testid^="video-edit-text-"]').first();
				}
			}
			expect(editedPart, 'a composed part has an editable text').toBeGreaterThanOrEqual(0);
			log(`edited part index: ${editedPart}`);
			await textInput.fill(NEW_TEXT);
			await expect(overlay.getByTestId('video-edit-pending-count')).toContainText(/1/);
			await screenshot(page, 'composed-edit-text', { fullPage: false });

			const userMessages = page.getByTestId('message-user');
			const before = await userMessages.count();
			const repliesBefore = await page.getByTestId('message-assistant').count();
			await overlay.getByTestId('video-edit-apply').click();
			await expect.poll(() => userMessages.count(), { timeout: 60_000 }).toBeGreaterThan(before);
			log('edit follow-up message sent');
			await closeOverlay(page, overlay);
			await expectChangeCard(page, screenshot, 'composed-change-card', 'edit', new RegExp(NEW_TEXT), log);
			await expectNewReplyFromGemini(page, repliesBefore, log, CHANGE_TIMEOUT);
			overlay = await openChangedVideo(page, overlay, firstDigest, CHANGE_TIMEOUT, log);
			await screenshot(page, 'composed-version-two', { fullPage: false });
			await saveVideo(page, overlay, 'composed-v2.mp4', log);
		} finally {
			writeEmbedConsole();
			if (process.env.KEEP_VIDEOS_CHAT !== '1') {
				await closeOverlay(page, overlay);
				await deleteActiveChat(page, log);
			}
		}
	});

	// contract-test: direct surface=gui.web assertions=videos-generate.generative.clip,videos-generate.result.video-with-timeline,videos-generate.timeline.below-the-video,videos-generate.change.extend-generated-clip,videos-generate.change.same-video-next-version
	test('generative clip, extend at the end', async ({ page }) => {
		test.setTimeout(1_800_000);
		skipWithoutCredentials(test, TEST_EMAIL, TEST_PASSWORD, TEST_OTP_KEY);
		const log = createSignupLogger('videos-generate-generative');
		const screenshot = createStepScreenshotter(log, { filenamePrefix: 'videos-generate-generative' });
		attachConsoleListeners(page);
		attachNetworkListeners(page);

		await loginToTestAccount(page, log, screenshot);
		await startNewChat(page, log);
		let overlay = page.getByTestId('embed-fullscreen-overlay').last();
		try {
			await sendWithGemini(page, GENERATIVE_PROMPT, log, screenshot, 'clip');
			await screenshotProgress(page, screenshot, 'clip-progress', log);
			await expect(page.locator(FINISHED_VIDEO_CARD).first()).toBeVisible({ timeout: GENERATIVE_TIMEOUT });
			await expectReplyFromGemini(page, log, GENERATIVE_TIMEOUT);
			await expectFinishedCard(page, log);
			await screenshot(page, 'clip-card-finished');

			overlay = await openNewestVideo(page);
			await expect(overlay.getByTestId('video-generate-fullscreen')).toHaveAttribute('data-made-by', 'generative');
			const timeline = overlay.getByTestId('video-timeline');
			await expect(timeline.getByTestId('video-timeline-part')).toHaveCount(1);
			await expect(overlay.getByTestId('video-timeline-extend-start')).toBeVisible();
			await expect(overlay.getByTestId('video-timeline-extend-end')).toBeVisible();
			await screenshot(page, 'generative-fullscreen-timeline', { fullPage: false });
			await saveVideo(page, overlay, 'generative-v1.mp4', log);
			const firstDigest = await shownVideoDigest(overlay);

			await overlay.getByTestId('video-timeline-extend-end').click();
			await overlay.getByTestId('video-extend-input').fill(EXTEND_TEXT);
			await screenshot(page, 'generative-extend-field', { fullPage: false });
			const userMessages = page.getByTestId('message-user');
			const before = await userMessages.count();
			const repliesBefore = await page.getByTestId('message-assistant').count();
			await overlay.getByTestId('video-extend-send').click();
			await expect.poll(() => userMessages.count(), { timeout: 60_000 }).toBeGreaterThan(before);
			log('extend follow-up message sent');
			await closeOverlay(page, overlay);
			await expectChangeCard(page, screenshot, 'generative-change-card', 'extend_end', /camera rises above the fog/, log);
			await expectNewReplyFromGemini(page, repliesBefore, log, CHANGE_TIMEOUT);
			overlay = await openChangedVideo(page, overlay, firstDigest, CHANGE_TIMEOUT, log);
			await expect(overlay.getByTestId('video-timeline').getByTestId('video-timeline-part')).toHaveCount(2, { timeout: 30_000 });
			await screenshot(page, 'generative-version-two', { fullPage: false });
			await saveVideo(page, overlay, 'generative-v2.mp4', log);
		} finally {
			if (process.env.KEEP_VIDEOS_CHAT !== '1') {
				await closeOverlay(page, overlay);
				await deleteActiveChat(page, log);
			}
		}
	});

	// contract-test: direct surface=gui.web assertions=videos-generate.routing.generative-or-composed,videos-generate.composed.author-writes-composition,videos-generate.result.video-with-timeline
	test('composed video from pictures in the chat', async ({ page }) => {
		test.setTimeout(1_800_000);
		skipWithoutCredentials(test, TEST_EMAIL, TEST_PASSWORD, TEST_OTP_KEY);
		const log = createSignupLogger('videos-generate-pictures');
		const screenshot = createStepScreenshotter(log, { filenamePrefix: 'videos-generate-pictures' });
		attachConsoleListeners(page);
		attachNetworkListeners(page);

		await loginToTestAccount(page, log, screenshot);
		await startNewChat(page, log);
		let overlay = page.getByTestId('embed-fullscreen-overlay').last();
		try {
			await sendWithGemini(page, PICTURES_PROMPT, log, screenshot, 'pictures');
			await expect.poll(() => page.locator(FINISHED_IMAGE_CARD).count(), { timeout: GENERATIVE_TIMEOUT })
				.toBeGreaterThanOrEqual(2);
			await expectReplyFromGemini(page, log, GENERATIVE_TIMEOUT);
			await screenshot(page, 'pictures-generated');

			await sendWithGemini(page, PICTURES_VIDEO_PROMPT, log, screenshot, 'pictures-video');
			await expect(page.locator(FINISHED_VIDEO_CARD).first()).toBeVisible({ timeout: COMPOSED_TIMEOUT });
			await expectReplyFromGemini(page, log, COMPOSED_TIMEOUT);

			overlay = await openNewestVideo(page);
			await expect(overlay.getByTestId('video-generate-fullscreen')).toHaveAttribute('data-made-by', 'composed');
			const parts = overlay.getByTestId('video-timeline').getByTestId('video-timeline-part');
			expect(await parts.count()).toBeGreaterThanOrEqual(2);
			log(`timeline parts: ${await parts.count()}`);
			await parts.nth(1).click();
			await screenshot(page, 'pictures-video-fullscreen', { fullPage: false });
			await saveVideo(page, overlay, 'composed-pictures.mp4', log);
		} finally {
			if (process.env.KEEP_VIDEOS_CHAT !== '1') {
				await closeOverlay(page, overlay);
				await deleteActiveChat(page, log);
			}
		}
	});
});
