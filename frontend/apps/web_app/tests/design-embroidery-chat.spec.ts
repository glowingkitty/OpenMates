/* eslint-disable @typescript-eslint/no-require-imports */
export {};

/**
 * Design embroidery chat E2E (real inference, dev server only): the assistant
 * (Gemini 3.8 Flash, picked through the @ mention dropdown) first creates a
 * flat SVG graphic, then calls design.embroidery on it. The result card shows
 * the stitch preview with size and stitch count, the opened view shows the
 * Stitches/Graphic switch, numbers, threads and five downloads, and the PES
 * download hands the browser a non-empty .pes file.
 *
 * Run through scripts/design_embroidery_web_real_test.py (personal dev test
 * account, leases, installed Chromium, output outside the repository).
 *
 * REQUIRED ENV VARS:
 * - OPENMATES_TEST_ACCOUNT_EMAIL
 * - OPENMATES_TEST_ACCOUNT_PASSWORD
 * - OPENMATES_TEST_ACCOUNT_OTP_KEY
 * - PLAYWRIGHT_TEST_BASE_URL
 */

const fs = require('node:fs');

const { test, expect, attachConsoleListeners, attachNetworkListeners } = require('./console-monitor');

const {
	createSignupLogger,
	createStepScreenshotter,
	getTestAccount
} = require('./signup-flow-helpers');

const {
	loginToTestAccount,
	startNewChat,
	sendMessage,
	deleteActiveChat,
	focusMessageEditor
} = require('./helpers/chat-test-helpers');
const { skipWithoutCredentials } = require('./helpers/env-guard');

const { email: TEST_EMAIL, password: TEST_PASSWORD, otpKey: TEST_OTP_KEY } = getTestAccount(1);

const MODEL_QUERY = 'gemini-3.8-flash';
const MODEL_NAME = /Gemini 3\.8 Flash/i;
const LOGO_PROMPT =
	'Create a simple flat three-colour logo of a fox head as an SVG graphic. No gradients, no text.';
const EMBROIDERY_PROMPT = 'Make this ready for our embroidery machine, 9 cm wide.';
const ANSWER_TIMEOUT = 420_000;
const FORMATS = ['dst', 'pes', 'exp', 'jef', 'vp3'];
// Either source is valid for design.embroidery: a generated SVG image or an SVG code embed.
const FINISHED_GRAPHIC = [
	'[data-testid="embed-preview"][data-app-id="images"][data-status="finished"] [data-testid="image-generate-preview-image"]',
	'[data-testid="embed-preview"][data-app-id="code"][data-status="finished"] [data-testid="svg-embed-image"]'
].join(', ');

/** Insert the Gemini 3.8 Flash mention through the dropdown, then send the prompt after it. */
async function sendWithGemini(page: any, prompt: string, log: any, screenshot: any, label: string) {
	const editor = page.getByTestId('message-field').last().getByTestId('message-editor');
	await expect(editor).toBeVisible();
	await focusMessageEditor(editor);
	await page.keyboard.insertText(`@${MODEL_QUERY}`);
	const dropdown = page.getByTestId('mention-dropdown');
	await expect(dropdown).toBeVisible({ timeout: 10_000 });
	await expect(dropdown.getByTestId('mention-result-name').filter({ hasText: MODEL_NAME }).first())
		.toBeVisible({ timeout: 10_000 });
	await page.keyboard.press('Tab');
	await expect(dropdown).not.toBeVisible({ timeout: 3000 });
	await sendMessage(page, ` ${prompt}`, log, screenshot, label, { preserveExistingContent: true });
}

/** The newest finished assistant reply must have been generated by Gemini 3.8 Flash. */
async function expectReplyFromGemini(page: any, log: any) {
	await expect(page.getByTestId('typing-indicator')).not.toBeVisible({ timeout: ANSWER_TIMEOUT });
	const generatedBy = page.getByTestId('message-assistant').last().getByTestId('generated-by');
	await expect(generatedBy).toBeVisible({ timeout: 120_000 });
	await expect(generatedBy).toContainText(MODEL_NAME);
	log(`reply generated by: ${(await generatedBy.textContent())?.trim()}`);
}

// contract-test: direct surface=gui.web assertions=design-embroidery.request.vector-source,design-embroidery.result.view-and-download,design-embroidery.result.complete-and-truthful
test('assistant turns a vector graphic into embroidery files that show and download', async ({ page }) => {
	test.setTimeout(1_200_000);
	skipWithoutCredentials(test, TEST_EMAIL, TEST_PASSWORD, TEST_OTP_KEY);
	const log = createSignupLogger('design-embroidery-chat');
	const screenshot = createStepScreenshotter(log, { filenamePrefix: 'design-embroidery-chat' });
	attachConsoleListeners(page);
	attachNetworkListeners(page);

	await loginToTestAccount(page, log, screenshot);
	await startNewChat(page, log);
	const overlay = page.getByTestId('embed-fullscreen-overlay').last();
	try {
		await sendWithGemini(page, LOGO_PROMPT, log, screenshot, 'logo');
		await expect(page.locator(FINISHED_GRAPHIC).first()).toBeVisible({ timeout: ANSWER_TIMEOUT });
		await expectReplyFromGemini(page, log);
		await screenshot(page, 'vector-graphic-created');

		await sendWithGemini(page, EMBROIDERY_PROMPT, log, screenshot, 'embroidery');
		const preview = page.locator('[data-testid="design-embroidery-preview"][data-status="finished"]').last();
		await expect(preview).toBeVisible({ timeout: ANSWER_TIMEOUT });
		// The innermost embed card around the embroidery preview (not a parent group card).
		const card = preview.locator('xpath=ancestor::*[@data-testid="embed-preview"][1]');
		await expectReplyFromGemini(page, log);

		const image = card.getByTestId('design-embroidery-preview-image');
		await expect(image).toBeVisible({ timeout: 60_000 });
		await expect
			.poll(() => image.evaluate((element: HTMLImageElement) => element.naturalWidth))
			.toBeGreaterThan(0);
		const numbers = card.getByTestId('design-embroidery-numbers');
		await expect(numbers).toContainText(/\d+\s*×\s*\d+\s*mm/);
		await expect(numbers).toContainText(/[\d.,]+\s*stitch/i);
		log(`card numbers: ${await numbers.textContent()}`);
		await card.scrollIntoViewIfNeeded();
		await screenshot(page, 'embroidery-card', { fullPage: false });

		// Assistant result cards in chat are groups; the expand tool opens the fullscreen.
		if ((await card.getAttribute('role')) === 'button') await card.click();
		else {
			await card.hover();
			await card.getByTestId('result-preview-expand').click();
		}
		await expect(overlay).toBeVisible({ timeout: 30_000 });
		const media = overlay.getByTestId('design-embroidery-fullscreen');
		await expect(media).toBeVisible({ timeout: 30_000 });
		await expect(media).toHaveAttribute('data-status', 'finished');
		const fullImage = overlay.getByTestId('design-embroidery-image');
		await expect(fullImage).toHaveAttribute('data-view', 'stitches');
		await expect
			.poll(() => fullImage.evaluate((element: HTMLImageElement) => element.naturalWidth), { timeout: 60_000 })
			.toBeGreaterThan(0);
		await expect(overlay.getByTestId('design-embroidery-view-stitches')).toBeVisible();
		await expect(overlay.getByTestId('design-embroidery-view-graphic')).toBeVisible();
		const size = overlay.getByTestId('design-embroidery-size');
		const stitches = overlay.getByTestId('design-embroidery-stitch-count');
		await expect(size).toContainText(/\d+\s*×\s*\d+\s*mm/);
		await expect(stitches).toContainText(/\d/);
		log(`opened view size: ${(await size.textContent())?.trim()} stitches: ${(await stitches.textContent())?.trim()}`);
		await screenshot(page, 'embroidery-fullscreen-top', { fullPage: false });

		expect(await overlay.getByTestId('design-embroidery-thread').count()).toBeGreaterThan(0);
		for (const format of FORMATS) {
			const button = overlay.getByTestId(`design-embroidery-download-${format}`);
			await button.scrollIntoViewIfNeeded();
			await expect(button).toBeVisible();
			await expect(button).toBeEnabled();
		}
		await overlay.getByTestId('design-embroidery-downloads').scrollIntoViewIfNeeded();
		await screenshot(page, 'embroidery-fullscreen-downloads', { fullPage: false });

		const downloadPromise = page.waitForEvent('download', { timeout: 60_000 });
		await overlay.getByTestId('design-embroidery-download-pes').click();
		const download = await downloadPromise;
		const filename = download.suggestedFilename();
		expect(filename.toLowerCase()).toMatch(/\.pes$/);
		const downloadedPath = await download.path();
		expect(downloadedPath, 'download finished and was saved').toBeTruthy();
		const bytes = fs.statSync(downloadedPath).size;
		expect(bytes).toBeGreaterThan(0);
		log(`downloaded file: ${filename} (${bytes} bytes)`);
		await expect(overlay.getByTestId('design-embroidery-download-pes-error')).toHaveCount(0);
		await screenshot(page, 'embroidery-pes-downloaded', { fullPage: false });

		// The main call to action saves every format in one ZIP.
		const allButton = overlay.getByTestId('design-embroidery-download-all');
		await allButton.scrollIntoViewIfNeeded();
		await expect(allButton).toBeVisible();
		const zipPromise = page.waitForEvent('download', { timeout: 90_000 });
		await allButton.click();
		const zip = await zipPromise;
		expect(zip.suggestedFilename().toLowerCase()).toMatch(/\.zip$/);
		const zipPath = await zip.path();
		expect(zipPath, 'ZIP download finished and was saved').toBeTruthy();
		const zipBytes = fs.statSync(zipPath).size;
		expect(zipBytes, 'ZIP holds the five machine files').toBeGreaterThan(bytes);
		log(`downloaded file: ${zip.suggestedFilename()} (${zipBytes} bytes)`);
		await expect(overlay.getByTestId('design-embroidery-download-all-error')).toHaveCount(0);
		await screenshot(page, 'embroidery-all-downloaded', { fullPage: false });
	} finally {
		if (process.env.KEEP_EMBROIDERY_CHAT !== '1') {
			if (await overlay.isVisible().catch(() => false)) {
				await overlay.getByTestId('embed-minimize').click().catch(() => page.keyboard.press('Escape'));
				await expect(overlay).toBeHidden({ timeout: 10_000 }).catch(() => undefined);
			}
			await deleteActiveChat(page, log);
		}
	}
});
