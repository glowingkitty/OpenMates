import { expect, test } from '../helpers/cookie-audit';
import { waitForComponentPreview } from '../helpers/component-preview';

// playwright-account: not_required reason=isolated_component_preview

const PROMPT = 'Put the sun logo in the bottom right corner, small, and make the hills greener';
const viewports = [{ name: '390', width: 390, height: 844 }, { name: '1280', width: 1280, height: 900 }];

for (const viewport of viewports) {
  test.describe(`images.modify at ${viewport.name}px`, () => {
    test.use({ viewport: { width: viewport.width, height: viewport.height } });
    const width = viewport.width === 390 ? 340 : 600;

    async function open(page: import('@playwright/test').Page, component: string, variant: string) {
      await page.goto(`/dev/preview/embeds/images/${component}?chrome=0&variant=${variant}&width=${width}`);
      await waitForComponentPreview(page);
      await expect(page.getByText('flux-schnell')).toHaveCount(0);
      await expect(page.getByText(/Generated by/)).toHaveCount(0);
    }

    // contract-test: supporting surface=gui.web assertions=images-modify.progress.shown-while-running
    test('card names the writing step and shows no picture yet', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedPreview', 'modifyWriting');
      await expect(page.getByTestId('image-modify-step')).toHaveText('Writing the edit…');
      await expect(page.getByTestId('image-modify-draft')).toHaveCount(0);
      await testInfo.attach(`modify-writing-card-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.progress.shown-while-running
    test('card shows the computed draft with the checking step', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedPreview', 'modifyCheckingWithDraft');
      await expect(page.getByTestId('image-modify-step')).toHaveText('Checking the result…');
      const draft = page.getByTestId('image-modify-draft');
      await expect(draft).toBeVisible();
      await expect(draft).toHaveAttribute('src', /^data:image\/jpeg;base64,/);
      await expect(page.getByText('Edited image')).toBeVisible();
      await expect(draft).toHaveCSS('object-fit', 'cover');
      await expect.poll(() => draft.evaluate((el: HTMLImageElement) => el.naturalWidth)).toBeGreaterThan(0);
      await testInfo.attach(`modify-checking-card-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.progress.shown-while-running
    test('card shows the attempt number from the second attempt on', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedPreview', 'modifyCorrecting');
      await expect(page.getByTestId('image-modify-step')).toHaveText('Correcting… · attempt 2');
      await expect(page.getByTestId('image-modify-draft')).toBeVisible();
      await testInfo.attach(`modify-correcting-card-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.result.normal-image
    test('finished card is a normal image without progress', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedPreview', 'modifyFinished');
      await expect(page.getByTestId('image-generate-preview-image')).toBeVisible();
      await expect(page.getByTestId('image-modify-step')).toHaveCount(0);
      await expect(page.getByTestId('image-modify-draft')).toHaveCount(0);
      await testInfo.attach(`modify-finished-card-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.result.normal-image
    test('failed card shows the error instead of progress', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedPreview', 'modifyFailed');
      await expect(page.getByText('The edit could not be completed')).toBeVisible();
      await expect(page.getByTestId('image-modify-step')).toHaveCount(0);
      await testInfo.attach(`modify-failed-card-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.progress.shown-while-running
    test('opened view shows step and draft while running', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedFullscreen', 'modifyCheckingWithDraft');
      await expect(page.getByTestId('image-modify-step')).toHaveText('Checking the result…');
      await expect(page.getByTestId('image-modify-step')).toBeInViewport();
      await expect(page.getByTestId('image-modify-draft')).toBeVisible();
      await expect(page.getByTestId('image-modify-draft')).toHaveCSS('object-fit', 'contain');
      await testInfo.attach(`modify-checking-opened-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.progress.shown-while-running
    test('opened view names the writing step without a picture', async ({ page }) => {
      await open(page, 'ImageGenerateEmbedFullscreen', 'modifyWriting');
      await expect(page.getByTestId('image-modify-step')).toHaveText('Writing the edit…');
      await expect(page.getByTestId('image-modify-draft')).toHaveCount(0);
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.result.normal-image
    test('opened finished result lists no unmet requirements when accepted', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedFullscreen', 'modifyFinished');
      await expect(page.getByRole('img', { name: PROMPT }).first()).toBeVisible();
      await expect(page.getByTestId('image-modify-unmet')).toHaveCount(0);
      await testInfo.attach(`modify-finished-opened-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });

    // contract-test: supporting surface=gui.web assertions=images-modify.result.normal-image
    test('opened result lists the unmet requirements in plain words', async ({ page }, testInfo) => {
      await open(page, 'ImageGenerateEmbedFullscreen', 'modifyUnmet');
      const unmet = page.getByTestId('image-modify-unmet');
      await unmet.scrollIntoViewIfNeeded();
      await expect(unmet).toBeVisible();
      await expect(unmet).toContainText('The logo is fully visible in the bottom right corner');
      await expect(unmet).toContainText('The hills are clearly greener than before');
      await testInfo.attach(`modify-unmet-opened-${viewport.name}`, { body: await page.screenshot(), contentType: 'image/png' });
    });
  });
}
