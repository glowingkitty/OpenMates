struct Passcode(String);
impl Terminal for Passcode {
    fn print(&mut self, _: &str) -> Result<(), CliError> {
        Ok(())
    }
    async fn line(&mut self, _: &str) -> Result<String, CliError> {
        unreachable!()
    }
    async fn secret(&mut self, question: &str) -> Result<Zeroizing<String>, CliError> {
        assert_eq!(question, "Connected account import passcode: ");
        Ok(Zeroizing::new(self.0.clone()))
    }
    fn env(&self, _: &str) -> Option<Zeroizing<String>> {
        None
    }
}
fn invalid(result: Result<CliOutput, CliError>) -> String {
    match result {
        Err(CliError::Invalid(message)) => message,
        _ => panic!("expected invalid input"),
    }
}

#[tokio::test]
async fn import_prompts_for_the_passcode_and_refuses_flags_and_teams() {
    let args = [
        "openmates",
        "connected-accounts",
        "import",
        "--payload",
        TRANSFER,
    ];
    assert!(supported(&parsed(&args)));
    assert!(super::super::super::handlers::requirements(&parsed(&args)).supported);
    let (mut client, server) = mock(vec![
        serde_json::json!({"valid":true}),
        serde_json::json!({"success":true,"ws_token":"synthetic","user":{"id":"owner"}}),
        serde_json::json!({"id":"stored-1"}),
    ])
    .await;
    let output = execute_with(&parsed(&args), &mut client, &mut Passcode("2468".into()))
        .await
        .ok()
        .unwrap();
    assert_eq!(
        output.stdout,
        "Connected account imported.\nProvider: google_calendar\nApp: google_calendar\nValidation: harmless read succeeded\n"
    );
    let requests = server.await.unwrap();
    assert!(
        requests[2].starts_with("POST /v1/connected-accounts ")
            && !requests[2].contains("secret-refresh")
    );
    for (extra, message) in [
        (
            vec!["--team", "t1"],
            "Team connected accounts are not supported yet. Use personal connected accounts or retry after Teams connected-account support ships.",
        ),
        (
            vec!["--passcode", "2468"],
            "Connected account import passcodes must be entered through the hidden prompt, not a command-line flag.",
        ),
    ] {
        let mut argv = args.to_vec();
        argv.extend(extra);
        assert_eq!(
            invalid(execute_with(&parsed(&argv), &mut client, &mut Passcode("x".into())).await),
            message
        );
    }
    assert_eq!(
        invalid(
            execute_with(
                &parsed(&["openmates", "connected-accounts", "import"]),
                &mut client,
                &mut Passcode("x".into())
            )
            .await
        ),
        "Missing --payload. Paste the command generated by connected account settings."
    );
}

#[test]
fn revolut_consent_and_dry_run_need_no_account() {
    let consent = parsed(&[
        "openmates",
        "connect-account",
        "revolut-business",
        "consent-url",
        "--client-id",
        "cid",
        "--json",
    ]);
    assert!(is_public(&consent) && super::super::super::docs::is_public(&consent));
    let value: serde_json::Value =
        serde_json::from_str(&execute_public(&consent).ok().unwrap().stdout).unwrap();
    assert_eq!(value["environment"], "sandbox");
    assert!(
        value["consent_url"]
            .as_str()
            .unwrap()
            .starts_with("https://sandbox-business.revolut.com/app-confirm?client_id=cid&")
    );
    let dry = parsed(&[
        "openmates",
        "connect-account",
        "revolut",
        "exchange-code",
        "--client-id",
        "cid",
        "--code",
        "abc",
        "--dry-run",
        "--production",
    ]);
    assert_eq!(
        execute_public(&dry).ok().unwrap().stdout,
        "Revolut Business authorization-code exchange dry run is valid.\nClientID: cid\nPrivate key: ~/.openmates/revolut-business/production/privatecert.pem\n"
    );
    let live = parsed(&[
        "openmates",
        "connect-account",
        "revolut",
        "exchange-code",
        "--client-id",
        "cid",
        "--code",
        "abc",
    ]);
    assert!(matches!(
        execute_public(&live),
        Err(CliError::Unsupported { .. })
    ));
    assert_eq!(
        invalid(execute_public(&parsed(&[
            "openmates",
            "connect-account",
            "revolut",
            "consent-url"
        ]))),
        "Missing --client-id <ClientID>."
    );
}
