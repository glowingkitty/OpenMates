// Version-wins plans: pins the real flag-off TypeScript (chatSyncVersionPlans.ts)
// to web_sync/versions_vectors.json, which the shared Rust module
// (web_sync/versions.rs) replays in cargo. Each vector request is exactly what
// the flag-on page adapter (rustCore/sync/versionOps.ts) sends, so the adapter
// answered from the vectors must return the TypeScript result; only version
// counters may cross. On drift the test prints the regenerated vectors after
// VERSION_PLAN_VECTORS_JSON=.
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it, vi } from "vitest";

const calls = vi.hoisted(() => ({
  capture: null as null | ((op: string, request: unknown) => unknown),
}));

vi.mock("../rustCore/sync/syncUnitClient", () => ({
  syncCall: async (op: string, request: unknown) => {
    if (!calls.capture) throw new Error("protocol");
    return calls.capture(op, JSON.parse(JSON.stringify(request)));
  },
}));

import * as ts from "../chatSyncVersionPlans";
import * as rust from "../rustCore/sync/versionOps";
import type { Chat } from "../../types/chat";

const VECTORS = resolve(__dirname, "../../../../../../packages/openmates-rust/src/web_sync/versions_vectors.json");

type Local = Record<string, unknown>;
const METADATA: [string, Local, Record<string, unknown> | undefined][] = [
  ["no-versions", { messages_v: 3, title_v: 2, encrypted_title: "ct" }, undefined],
  ["empty-versions", { messages_v: 3, title_v: 2 }, {}],
  ["newer-revision", { metadata_v: 4, title_v: 2, messages_v: 5, draft_v: 1 }, { metadata_v: 5, title_v: 6, messages_v: 6, draft_v: 2 }],
  ["older-revision", { metadata_v: 4, title_v: 2, messages_v: 5, draft_v: 1 }, { metadata_v: 3, title_v: 9, messages_v: 4, draft_v: 1 }],
  ["equal-revision-no-title", { metadata_v: 4, title_v: 7, messages_v: 1 }, { metadata_v: 4 }],
  ["legacy-older-metadata", { title_v: 3, messages_v: 2 }, { metadata_v: 2, title_v: 1 }],
  ["legacy-title-ahead", { title_v: 3, messages_v: 2 }, { title_v: 4 }],
  ["title-behind", { title_v: 3 }, { title_v: 3, draft_v: 0 }],
  ["metadata-zero-falls-back", { metadata_v: 0, title_v: 5 }, { metadata_v: 5 }],
  ["null-versions", { messages_v: 0, title_v: 0, draft_v: 0 }, { metadata_v: null, title_v: null, messages_v: null, draft_v: null }],
  ["local-missing-counters", { encrypted_chat_summary: "ct" }, { messages_v: 1, draft_v: 1, title_v: 1 }],
  ["local-null-counters", { messages_v: null, title_v: null, metadata_v: null, draft_v: null }, { metadata_v: 0, messages_v: 0 }],
];
const DRAFT_DELETED: [string, Local, number | null | undefined][] = [
  ["empty-versionless", {}, undefined],
  ["versioned-local-versionless", { draft_v: 2 }, undefined],
  ["cleared-local-versionless", { cleared_draft_v: 3 }, undefined],
  ["stale", { draft_v: 2 }, 1],
  ["equal", { draft_v: 2, encrypted_draft_md: "ct" }, 2],
  ["newer-than-cleared", { draft_v: 2, cleared_draft_v: 5 }, 6],
  ["stale-against-cleared", { draft_v: 2, cleared_draft_v: 5 }, 4],
  ["cleared-equal", { draft_v: 0, cleared_draft_v: 4 }, 4],
  ["null-incoming-stale", { draft_v: 3 }, null],
  ["null-incoming-empty", {}, null],
  ["null-local", { draft_v: null, cleared_draft_v: null }, 0],
  ["zero-local-versionless", { draft_v: 0, cleared_draft_v: 0 }, undefined],
];
const MESSAGES: [string, number | null | undefined, (number | null)[]][] = [
  ["undefined-local", undefined, [3]],
  ["behind", 5, [3]],
  ["equal", 5, [5]],
  ["batch-ahead", 2, [7, 4]],
  ["batch-local-count-wins", 2, [3, 9]],
  ["zeros", 0, [0, 0]],
  ["null-local-null-candidate", null, [null, 2]],
  ["no-candidates", 4, []],
];

async function captured<T>(call: () => Promise<T>, answer: unknown): Promise<{ request: unknown; result: T }> {
  let request: unknown;
  calls.capture = (_op, r) => ((request = r), answer);
  const result = await call();
  calls.capture = null;
  return { request, result };
}

/** Vectors regenerated from the real TypeScript; requests are the adapter's own. */
async function regenerate() {
  const out = { note: "Generated by chatSyncVersionPlansVectors.test.ts from chatSyncVersionPlans.ts.", metadata: [] as unknown[], draftDeleted: [] as unknown[], messages: [] as unknown[] };
  for (const [name, local, versions] of METADATA) {
    const response = ts.metadataVersionPlanTs(local as unknown as Chat, versions as ts.MetadataVersions);
    const { request } = await captured(() => rust.metadataVersions(local as unknown as Chat, versions as ts.MetadataVersions), response);
    out.metadata.push({ name, request, response: JSON.parse(JSON.stringify(response)) });
  }
  for (const [name, local, draftV] of DRAFT_DELETED) {
    const response = ts.draftDeletedPlanTs(local as unknown as Chat, draftV as number);
    const { request } = await captured(() => rust.draftDeleted(local as unknown as Chat, draftV as number), response);
    out.draftDeleted.push({ name, request, response: JSON.parse(JSON.stringify(response)) });
  }
  for (const [name, local, candidates] of MESSAGES) {
    const response = ts.messagesVersionTs(local, candidates as number[]);
    const { request } = await captured(() => rust.messagesVersion(local, candidates as number[]), response);
    out.messages.push({ name, request, response: JSON.parse(JSON.stringify(response)) });
  }
  return out;
}

describe("version-wins plan vectors", () => {
  // contract-test: supporting surface=gui.web assertions=sync.client.shared-rust-policy
  it("matches the committed vectors generated from the flag-off TypeScript", async () => {
    const regenerated = await regenerate();
    const committed = JSON.parse(readFileSync(VECTORS, "utf8"));
    if (JSON.stringify(committed) !== JSON.stringify(regenerated)) {
      console.log(`VERSION_PLAN_VECTORS_JSON=${JSON.stringify(regenerated)}`);
    }
    expect(committed).toEqual(regenerated);
  });

  // contract-test: supporting surface=gui.web assertions=sync.client.shared-rust-policy
  it("answers the flag-on adapter from the vectors with the TypeScript result and sends only version counters", async () => {
    const committed = JSON.parse(readFileSync(VECTORS, "utf8"));
    const byRequest = (group: { request: unknown; response: unknown }[]) => (_op: string, request: unknown) => {
      const hit = group.find((c) => JSON.stringify(c.request) === JSON.stringify(request));
      if (!hit) throw new Error("protocol");
      return hit.response;
    };
    const allowed = new Set(["messages_v", "metadata_v", "title_v", "draft_v", "cleared_draft_v"]);
    for (const c of committed.metadata) {
      for (const part of [c.request.local, c.request.versions ?? {}]) {
        for (const key of Object.keys(part)) expect(allowed.has(key)).toBe(true);
      }
    }
    for (const c of committed.draftDeleted) for (const key of Object.keys(c.request.local)) expect(allowed.has(key)).toBe(true);

    calls.capture = byRequest(committed.metadata);
    for (const [, local, versions] of METADATA) {
      expect(await ts.metadataVersionPlanRust(local as unknown as Chat, versions as ts.MetadataVersions))
        .toEqual(ts.metadataVersionPlanTs(local as unknown as Chat, versions as ts.MetadataVersions));
    }
    calls.capture = byRequest(committed.draftDeleted);
    for (const [, local, draftV] of DRAFT_DELETED) {
      expect(await ts.draftDeletedPlanRust(local as unknown as Chat, draftV as number))
        .toEqual(ts.draftDeletedPlanTs(local as unknown as Chat, draftV as number));
    }
    calls.capture = byRequest(committed.messages);
    for (const [, local, candidates] of MESSAGES) {
      expect(await ts.messagesVersionRust(local, candidates as number[]))
        .toEqual(ts.messagesVersionTs(local, candidates as number[]));
    }
    calls.capture = null;
  });
});
