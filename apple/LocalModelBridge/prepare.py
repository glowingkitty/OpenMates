#!/usr/bin/env python3
"""Prepare pinned arm64 libraries in isolated platform directories; never download model weights.

The universal app's Intel compile/link settings never reference this directory.
All generated bytes stay under DERIVED_FILE_DIR and out of source provenance.
"""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import plistlib
import re
import shutil
import tempfile
import urllib.request
import zipfile

HERE = Path(__file__).resolve().parent
NAMES = {'executorch', 'backend_xnnpack', 'kernels_optimized',
         'kernels_quantized', 'kernels_torchao', 'threadpool'}
MAX_ARCHIVE_BYTES = 64 * 1024 * 1024
PLATFORMS = {
    'iphoneos': ('ios', None, 'ios-arm64', 'ios', 'arm64-apple-ios.swiftinterface'),
    'iphonesimulator': ('ios', 'simulator', 'ios-arm64-simulator', 'simulator', 'arm64-apple-ios-simulator.swiftinterface'),
    'macosx': ('macos', None, 'macos-arm64', 'macos', 'arm64-apple-macos.swiftinterface'),
}


def sha256(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for data in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(data)
    return digest.hexdigest()


def catalog(path):
    data = json.loads(Path(path).read_text())
    if data.get('schema_version') != 1 or data.get('version') != '1.5.0':
        raise ValueError('Unsupported bridge catalog')
    artifacts = data['artifacts']
    if len(artifacts) != len(NAMES) or {a['name'] for a in artifacts} != NAMES:
        raise ValueError('Missing or duplicate pinned CPU artifact')
    for artifact in artifacts:
        name = artifact['name']
        if artifact['url'] != 'https://ossci-ios.s3.amazonaws.com/executorch/' + name + '-1.5.0.zip':
            raise ValueError('Unpinned archive URL')
        if not re.fullmatch('[0-9a-f]{64}', artifact['sha256']):
            raise ValueError('Invalid archive checksum')
        expected = {platform: 'lib' + name + '_' + values[3] + '.a'
                    for platform, values in PLATFORMS.items()}
        if artifact['slice_libraries'] != expected:
            raise ValueError('Unexpected platform library names')
    if sha256(Path(path).parent / data['license']['path']) != data['license']['sha256']:
        raise ValueError('Upstream license checksum mismatch')
    return data


def should_prepare(platform, architectures):
    return platform in PLATFORMS and 'arm64' in architectures.split()


def find_cached_archive(artifact, roots):
    """Only reuse ZIP bytes that match the pinned SwiftPM checksum.

    Extracted SourcePackages trees have no trustworthy whole-archive checksum;
    do not treat an artifact pathname or SwiftPM receipt alone as verification.
    """
    checked = 0
    for root in roots:
        if not root.is_dir():
            continue
        for candidate in root.rglob('*.zip'):
            checked += 1
            if checked > 500:
                return None
            if candidate.is_file() and candidate.stat().st_size <= MAX_ARCHIVE_BYTES:
                if sha256(candidate) == artifact['sha256']:
                    return candidate
    return None


def get_archive(artifact, archives, cache_roots):
    archives.mkdir(parents=True, exist_ok=True)
    target = archives / (artifact['name'] + '-1.5.0.zip')
    if target.exists() and sha256(target) == artifact['sha256']:
        return target
    cached = find_cached_archive(artifact, cache_roots)
    if cached:
        shutil.copyfile(cached, target)
        return target
    # Only exact release SDK archives are fetched; no inference assets or inputs.
    fd, temporary = tempfile.mkstemp(prefix='bridge-download-', dir=str(archives))
    try:
        with os.fdopen(fd, 'wb') as output:
            with urllib.request.urlopen(artifact['url'], timeout=120) as response:
                if response.status != 200:
                    raise ValueError('SDK archive response rejected')
                length = response.headers.get('Content-Length')
                if length and int(length) > MAX_ARCHIVE_BYTES:
                    raise ValueError('SDK archive exceeds size limit')
                total = 0
                while True:
                    chunk = response.read(1024 * 1024)
                    if not chunk:
                        break
                    total += len(chunk)
                    if total > MAX_ARCHIVE_BYTES:
                        raise ValueError('SDK archive exceeds size limit')
                    output.write(chunk)
        if sha256(temporary) != artifact['sha256']:
            raise ValueError('Pinned SDK archive checksum mismatch')
        os.replace(temporary, target)
        return target
    finally:
        if Path(temporary).exists():
            Path(temporary).unlink()


def extract_slice(artifact, archive, destination, platform):
    # Verify immediately before using ZIP metadata or extraction, including cache reuse.
    if sha256(archive) != artifact['sha256']:
        raise ValueError('SDK archive checksum mismatch')
    name = artifact['name']
    supported_platform, variant, identifier, _, _ = PLATFORMS[platform]
    prefix = name + '.xcframework/'
    with zipfile.ZipFile(archive) as zipped:
        info = plistlib.loads(zipped.read(prefix + 'Info.plist'))
        matches = [item for item in info['AvailableLibraries']
                   if item['SupportedPlatform'] == supported_platform
                   and item.get('SupportedPlatformVariant') == variant
                   and item['SupportedArchitectures'] == ['arm64']]
        if len(matches) != 1 or matches[0]['LibraryIdentifier'] != identifier:
            raise ValueError('Unexpected pinned platform slice')
        if matches[0]['LibraryPath'] != artifact['slice_libraries'][platform]:
            raise ValueError('Pinned platform library metadata mismatch')
        slice_prefix = prefix + identifier + '/'
        for item in zipped.infolist():
            if not item.filename.startswith(slice_prefix) or item.is_dir():
                continue
            parts = Path(item.filename).parts
            if '..' in parts or Path(item.filename).is_absolute():
                raise ValueError('SDK archive contains unsafe path')
            if (item.external_attr >> 16) & 0o170000 == 0o120000:
                raise ValueError('SDK archive contains symlink')
            target = destination / item.filename
            # Compare against the verified ZIP member, not a cached receipt.
            # Unchanged header mtimes preserve Xcode's compiled module cache.
            if target.is_file():
                expected = hashlib.sha256()
                with zipped.open(item) as source:
                    for chunk in iter(lambda: source.read(1024 * 1024), b''):
                        expected.update(chunk)
                if sha256(target) == expected.hexdigest():
                    continue
            target.parent.mkdir(parents=True, exist_ok=True)
            with zipped.open(item) as source, target.open('wb') as output:
                shutil.copyfileobj(source, output)
    if not (destination / slice_prefix / artifact['slice_libraries'][platform]).is_file():
        raise ValueError('Platform library missing after extraction')


def prepare(data, output, cache_roots, platform):
    output.mkdir(parents=True, exist_ok=True)
    with (output / '.prepare.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        archives = output / 'archives'
        # Separate module maps, overlays and libraries by platform. Nothing is
        # copied into Xcode's flattened SourcePackages include directory.
        selected = output / platform
        for artifact in data['artifacts']:
            extract_slice(artifact, get_archive(artifact, archives, cache_roots), selected, platform)
        core = selected / 'executorch.xcframework' / PLATFORMS[platform][2]
        headers = core / 'Headers'
        module_map = (headers / 'module.modulemap').read_text()
        interface = core / 'ExecuTorch.swiftinterface'
        interface_text = interface.read_text()
        if 'module ExecuTorch' not in module_map or 'ExecuTorch/ExecuTorch.h' not in module_map:
            raise ValueError('ExecuTorch Clang module missing')
        if '-module-name ExecuTorch' not in interface_text or 'func forward' not in interface_text or 'class Tensor<' not in interface_text:
            raise ValueError('ExecuTorch Swift overlay missing')
        # Preserve the upstream overlay bytes; Swift imports its underlying ObjC module.
        modules = selected / 'Modules/ExecuTorch.swiftmodule'
        modules.mkdir(parents=True, exist_ok=True)
        overlay = modules / PLATFORMS[platform][4]
        if not overlay.is_file() or sha256(overlay) != sha256(interface):
            shutil.copyfile(interface, overlay)
        receipt = {'schema_version': 1, 'platform': platform, 'upstream_revision': data['upstream_revision'],
                   'artifacts': [{**a, 'verified': True} for a in data['artifacts']],
                   'module_map_sha256': sha256(headers / 'module.modulemap'),
                   'swift_interface_sha256': sha256(interface)}
        (selected / 'receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--catalog', type=Path, default=HERE / 'catalog.json')
    parser.add_argument('--validate-catalog', action='store_true')
    parser.add_argument('--output', type=Path)
    parser.add_argument('--source-packages', type=Path, action='append', default=[])
    args = parser.parse_args()
    data = catalog(args.catalog)
    if args.validate_catalog:
        print('Pinned LocalModelBridge catalog validated; no archives fetched.')
        return
    architectures = os.environ.get('ARCHS', '') + ' ' + os.environ.get('CURRENT_ARCH', '')
    platform = os.environ.get('PLATFORM_NAME', '')
    if not should_prepare(platform, architectures):
        return
    output = args.output or Path(os.environ['DERIVED_FILE_DIR']) / 'LocalModelBridge'
    roots = args.source_packages
    for key in ['CLONED_SOURCE_PACKAGES_DIR_PATH', 'SOURCE_PACKAGES_DIR']:
        if os.environ.get(key):
            roots.append(Path(os.environ[key]))
    if os.environ.get('BUILD_DIR'):
        build_dir = Path(os.environ['BUILD_DIR'])
        roots.extend(parent / 'SourcePackages' for parent in [build_dir] + list(build_dir.parents)[:3])
    prepare(data, output, roots, platform)
    print('Pinned ExecuTorch arm64 bridge prepared for ' + platform + '; x86_64 linkage is absent.')


if __name__ == '__main__':
    main()
